"""Macros and table for the external-price anchor test, from reports/unit_td/anchor_external.json.

Writes paper/generated/anchor_ext_numbers.tex (macros ``\\NumK...``, each with a source comment) and anchor_ext_table.tex.
Source: ``uv run python -m www_auto.anchor_external``. Run: ``uv run python -m www_paper.anchor_ext_macros``.
Slice tags: Stress = 2018-11-27 to 2019-05-31; years are spelled out because macro names cannot hold digits.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "anchor_ext_numbers.tex"
TABLE = GEN / "anchor_ext_table.tex"
REPORT = ROOT / "reports/unit_td/anchor_external.json"
HEADER = "% generated by www_paper.anchor_ext_macros; do not edit"
SRC = "reports/unit_td/anchor_external.json"
MINUS = "\\ensuremath{-}"
STRESS = "stress_2018-11-27_2019-05-31"
DIG = dict(zip("0123456789", ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine")))
YEARS = tuple(range(2018, 2024))


def _tag(y: int) -> str:
    return "Y" + "".join(DIG[c] for c in str(y))


SLICE_LIST = [(STRESS, "Stress", "Stress, 2018-11-27 to 2019-05-31")] + [(str(y), _tag(y), str(y)) for y in YEARS]


def _load() -> Any:
    return json.loads(REPORT.read_text())


def _num(v: float, d: int) -> str:
    s = f"{v:,.{d}f}"
    if s.startswith("-"):
        return s[1:] if not s.strip("-0.,") else MINUS + s[1:]
    return s


def _cell(v: float | None, d: int = 2) -> str:
    return "--" if v is None else _num(v, d)


def _ci(e: dict | None, key: str, d: int = 2) -> str:
    c = None if e is None else e.get(key)
    return "--" if c is None else f"[{_num(c[0], d)}, {_num(c[1], d)}]"


def _get(s: dict, *path: str) -> Any:
    for p in path:
        if not isinstance(s, dict) or p not in s:
            return None
        s = s[p]
    return s


def macros() -> list[tuple[str, str, str]]:
    r = _load()
    out: list[tuple[str, str, str]] = []

    def add(name: str, val: float | int | None, d: int, src: str) -> None:
        if val is not None:
            out.append((f"NumK{name}", _num(val, d), f"{SRC} {src}"))

    for key, tag, _ in SLICE_LIST:
        s = r["slices"][key]
        base = f"slices/{key}"
        for fr, F in (("hourly", "Hr"), ("daily", "Day")):
            a = _get(s, "adjusted_LDX", fr)
            add(f"{tag}{F}N", _get(a, "n"), 0, f"{base}/adjusted_LDX/{fr}/n")
            add(f"{tag}{F}SlopeD", _get(a, "slope_D_on_L", "est"), 2, f"{base}/adjusted_LDX/{fr}/slope_D_on_L/est")
            add(f"{tag}{F}SlopeAdj", _get(a, "slope_D_minus_X_on_L", "est"), 2, f"{base}/adjusted_LDX/{fr}/slope_D_minus_X_on_L/est")
            for blk, B in (("week", "Wk"), ("month", "Mo")):
                c = _get(a, "slope_D_minus_X_on_L", f"ci95_{blk}")
                if c:
                    add(f"{tag}{F}SlopeAdj{B}Lo", c[0], 2, f"{base}/adjusted_LDX/{fr}/slope_D_minus_X_on_L/ci95_{blk}[0]")
                    add(f"{tag}{F}SlopeAdj{B}Hi", c[1], 2, f"{base}/adjusted_LDX/{fr}/slope_D_minus_X_on_L/ci95_{blk}[1]")
            iv = _get(s, "iv_LDXE", fr)
            add(f"{tag}{F}IvAdj", _get(iv, "iv_slope_D_minus_X_on_L", "est"), 2, f"{base}/iv_LDXE/{fr}/iv_slope_D_minus_X_on_L/est")
            c = _get(iv, "iv_slope_D_minus_X_on_L", "ci95_week")
            if c:
                add(f"{tag}{F}IvAdjWkLo", c[0], 2, f"{base}/iv_LDXE/{fr}/iv_slope_D_minus_X_on_L/ci95_week[0]")
                add(f"{tag}{F}IvAdjWkHi", c[1], 2, f"{base}/iv_LDXE/{fr}/iv_slope_D_minus_X_on_L/ci95_week[1]")
        add(f"{tag}HoursBig", s.get("hours_big"), 0, f"{base}/hours_big (|L| >= 50 bps, hours with L, D, X)")
        for k, N in (("median_L", "MedL"), ("median_T", "MedT"), ("median_X", "MedX"), ("median_T_minus_X", "MedTmX")):
            add(f"{tag}{N}", s.get(k), 1, f"{base}/{k}")
        add(f"{tag}CorrTX", s.get("corr_T_X_hourly"), 2, f"{base}/corr_T_X_hourly")
        add(f"{tag}CorrTXDay", s.get("corr_T_X_daily"), 2, f"{base}/corr_T_X_daily")
        kb = r["kraken_btc_gap_vs_bitstamp"][key]
        add(f"{tag}KrakenBtcGapMedAbs", kb.get("median_abs"), 1, f"kraken_btc_gap_vs_bitstamp/{key}/median_abs")
        add(f"{tag}KrakenBtcGapMed", kb.get("median"), 1, f"kraken_btc_gap_vs_bitstamp/{key}/median")
        add(f"{tag}KrakenBtcGapBigPct", None if kb.get("share_abs_ge_50") is None else 100 * kb["share_abs_ge_50"], 2,
            f"kraken_btc_gap_vs_bitstamp/{key}/share_abs_ge_50, percent")
    cv = r["coverage_kraken_usdt_stress"]
    for k, N, d in (("hours_in_window", "CovHours", 0), ("hours_traded", "CovTraded", 0), ("traded_minutes", "CovMinutes", 0),
                    ("untraded_gap_runs", "CovGapRuns", 0), ("longest_untraded_gap_hours", "CovLongestGap", 0),
                    ("hours_traded_and_bitfinex_usdt", "CovOverlap", 0), ("median_minutes_per_traded_hour", "CovMedMin", 0)):
        add(N, cv[k], d, f"coverage_kraken_usdt_stress/{k}")
    add("CovSharePct", 100 * cv["share_hours_traded"], 2, "coverage_kraken_usdt_stress/share_hours_traded, percent")
    x = r["kraken_usdt_level_X"][STRESS]
    add("StressXMedian", x["median"], 1, f"kraken_usdt_level_X/{STRESS}/median")
    add("StressXMin", x["min"], 0, f"kraken_usdt_level_X/{STRESS}/min")
    add("CrosscheckHourMedAbs", r["crosscheck_60min_usdt_stress"]["median_abs_diff_bps"], 1, "crosscheck_60min_usdt_stress/median_abs_diff_bps")
    add("Draws", r["bootstrap"]["draws"], 0, "bootstrap/draws")
    return out


def numbers() -> str:
    lines = [HEADER]
    for name, val, src in macros():
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}} % {src}")
    return "\n".join(lines) + "\n"


def table() -> str:
    r = _load()
    rows = []
    for key, _, label in SLICE_LIST:
        s = r["slices"][key]
        h, d = _get(s, "adjusted_LDX", "hourly"), _get(s, "adjusted_LDX", "daily")
        iv = _get(s, "iv_LDXE", "daily")
        rows.append(" & ".join([
            label, _cell(_get(h, "n"), 0) if _get(h, "n") is not None else "--",
            _cell(_get(d, "slope_D_on_L", "est")),
            _cell(_get(d, "slope_D_minus_X_on_L", "est")), _ci(_get(d, "slope_D_minus_X_on_L"), "ci95_week"),
            _ci(_get(d, "slope_D_minus_X_on_L"), "ci95_month"),
            _cell(_get(iv, "iv_slope_D_minus_X_on_L", "est")),
            _cell(s.get("median_T"), 0), _cell(s.get("median_X"), 0), _cell(s.get("median_T_minus_X"), 0),
            _cell(s.get("corr_T_X_hourly"))]) + " \\\\")
    cap = ("External-price anchor test. $X=10^4\\log P_{\\mathrm{Kraken}}(\\mathrm{USDT/USD})$ is USDT's price on Kraken; "
           "$L$ is the Bitfinex--Bitstamp bitcoin gap, $D=10^4\\log P_{\\mathrm{Bfx}}(\\mathrm{USDT/USD})$ and $T=D-L$ (bps). "
           "Slopes are OLS on daily medians (hours where $L$, $D$, $X$ all exist); $D$ on $L$ reproduces Table~\\ref{tab:anchor} up to "
           "the hours in which Kraken traded; $(D-X)$ on $L$ has 95\\% block-bootstrap intervals over weeks and over months "
           "(1,000 draws; -- when fewer than five blocks); IV uses the Bitfinex--Coinbase ETH gap as instrument for $L$. "
           "Medians of $T$, $X$ and $T-X$ and corr$(T,X)$ (hourly) use hours with $|L|\\ge 50$ bps for the medians. "
           "If $T=X$, the $(D-X)$ slope is 1 and $T-X=0$.")
    return f"""{HEADER}
\\begin{{table*}}[t]
\\footnotesize
\\caption{{{cap}}}
\\label{{tab:anchor-ext}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lrrrllrrrrr@{{}}}}
\\toprule
Slice & Hours & $D$ on $L$ & $(D-X)$ on $L$ & 95\\% CI (weeks) & 95\\% CI (months) & IV & Med $T$ & Med $X$ & Med $T-X$ & corr$(T,X)$ \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    for path, text in ((NUMBERS, numbers()), (TABLE, table())):
        path.write_text(text)
        print(f"WROTE {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
