"""Macros and table for the anchored-test theory, from reports/theory/simulation.json and gmm_applied.json.

Writes paper/generated/theory_numbers.tex (macros ``\\NumG...``, each with a source comment) and theory_table.tex.
Sources: ``uv run python -m www_theory.applied`` and ``uv run python -m www_theory.simulate``.
Run: ``uv run python -m www_paper.theory_macros``.  Scenario tags: SOne..SSeven; digits are spelled out in macro names.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "theory_numbers.tex"
TABLE = GEN / "theory_table.tex"
SIM = ROOT / "reports/theory/simulation.json"
APP = ROOT / "reports/theory/gmm_applied.json"
HEADER = "% generated by www_paper.theory_macros; do not edit"
MINUS = "\\ensuremath{-}"
WORD = {"1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven"}


def num(v: float, d: int) -> str:
    s = f"{v:,.{d}f}"
    return s[1:] if s.startswith("-") and not s.strip("-0.,") else (MINUS + s[1:] if s.startswith("-") else s)


def pval(p: float | None) -> str:
    if p is None:
        return "--"
    return "\\ensuremath{<}0.001" if p < 0.001 else num(p, 3 if p < 0.01 else 2)


def ci(c: list[float]) -> str:
    return f"[{num(c[0], 3)}, {num(c[1], 3)}]"


def _specs() -> dict[str, tuple[str, str, str]]:
    """macro tag -> (section, spec key, human label)"""
    return {"BfxPrimary": ("bitfinex", "netted|eth_ltc_bch_etc", "Bitfinex, USDT netted with Kraken, 4 instruments"),
            "BfxEth": ("bitfinex", "netted|eth", "Bitfinex, USDT netted, ETH gap only"),
            "BfxNaive": ("bitfinex", "not_netted|eth_ltc_bch_etc", "Bitfinex, USDT not netted, 4 instruments"),
            "BusUsdt": ("binance_us", "usdt|netted|lags12", "Binance.US 2023, USDT netted"),
            "BusTwo": ("binance_us", "usdt_usdc|netted|lags12", "Binance.US Feb--Jul 2023, USDT and USDC netted"),
            "BusTwoRaw": ("binance_us", "usdt_usdc|not_netted|lags12", "Binance.US Feb--Jul 2023, USDT and USDC not netted")}


def macros() -> list[tuple[str, str, str]]:
    sim, app = json.loads(SIM.read_text()), json.loads(APP.read_text())
    out: list[tuple[str, str, str]] = []

    def add(name: str, val: str, src: str) -> None:
        out.append((f"NumG{name}", val, src))

    for tag, (sec, key, _) in _specs().items():
        r = app[sec]["specs"][key]
        src = f"reports/theory/gmm_applied.json {sec}/specs/{key}/"
        add(f"{tag}N", num(r["n"], 0), src + "n")
        add(f"{tag}Lam", num(r["lam"], 3), src + "lam")
        add(f"{tag}Lo", num(r["ci95"][0], 3), src + "ci95[0]")
        add(f"{tag}Hi", num(r["ci95"][1], 3), src + "ci95[1]")
        add(f"{tag}POne", pval(r["p_lam1"]), src + "p_lam1")
        add(f"{tag}PZero", pval(r["p_lam0"]), src + "p_lam0")
        add(f"{tag}J", num(r["J"], 2), src + "J")
        add(f"{tag}JDf", num(r["J_df"], 0), src + "J_df")
        add(f"{tag}JP", pval(r["J_p"]), src + "J_p")
        add(f"{tag}Ols", num(r["ols_first_anchor"]["lam"], 3), src + "ols_first_anchor/lam")
    b = app["bitfinex"]["specs"]["netted|eth"]["iv_first_instrument_first_anchor"]["bootstrap"]
    add("BfxBootLo", num(b["ci95"][0], 3), "reports/theory/gmm_applied.json bitfinex/specs/netted|eth/iv_first_instrument_first_anchor/bootstrap/ci95[0]")
    add("BfxBootHi", num(b["ci95"][1], 3), "reports/theory/gmm_applied.json bitfinex/specs/netted|eth/iv_first_instrument_first_anchor/bootstrap/ci95[1]")
    add("BfxBootBlock", num(b["block"], 0), "reports/theory/gmm_applied.json bitfinex/specs/netted|eth/iv_first_instrument_first_anchor/bootstrap/block")
    add("BfxHacLags", num(app["bitfinex"]["specs"]["netted|eth"]["hac_lags"], 0), "reports/theory/gmm_applied.json bitfinex/specs/netted|eth/hac_lags")
    cal = sim["calibration"]
    add("CalRhoC", num(cal["rho_c"], 3), "reports/theory/simulation.json calibration/rho_c (from reports/theory/calibration.json)")
    add("CalSigmaC", num(cal["sigma_c"], 0), "reports/theory/simulation.json calibration/sigma_c")
    add("SimReps", num(sim["reps"], 0), "reports/theory/simulation.json reps")
    add("SimHours", num(sim["hours"], 0), "reports/theory/simulation.json hours")
    add("SimBootReps", num(sim["scenarios"]["S1"]["bootstrap_iv"]["reps"], 0), "reports/theory/simulation.json scenarios/S1/bootstrap_iv/reps")
    for s, v in sim["scenarios"].items():
        t, src = "S" + WORD[s[1]], f"reports/theory/simulation.json scenarios/{s}/"
        for est, E in (("ols", "Ols"), ("iv", "Iv"), ("gmm", "Gmm")):
            add(f"{t}Bias{E}", num(v["estimators"][est]["bias"], 3), src + f"estimators/{est}/bias")
        g = v["estimators"]["gmm"]
        add(f"{t}RejOne", num(g["rej_lam1"], 2), src + "estimators/gmm/rej_lam1")
        add(f"{t}RejZero", num(g["rej_lam0"], 2), src + "estimators/gmm/rej_lam0")
        add(f"{t}Cover", num(g["coverage95"], 2), src + "estimators/gmm/coverage95")
        add(f"{t}CoverIv", num(v["estimators"]["iv"]["coverage95"], 2), src + "estimators/iv/coverage95")
        add(f"{t}CoverNw", num(v["estimators"]["iv_nw"]["coverage95"], 2), src + "estimators/iv_nw/coverage95")
        add(f"{t}CoverBoot", num(v["bootstrap_iv"]["coverage95"], 2), src + "bootstrap_iv/coverage95")
        add(f"{t}JRej", num(v["J_rejection_5pct"], 2), src + "J_rejection_5pct")
    return out


def numbers() -> str:
    return "\n".join([HEADER] + [f"\\newcommand{{\\{n}}}{{{v}}} % {s}" for n, v, s in macros()]) + "\n"


def table() -> str:
    sim, app = json.loads(SIM.read_text()), json.loads(APP.read_text())
    rows = []
    for s, v in sim["scenarios"].items():
        e = v["estimators"]
        rows.append(" & ".join([f"{s}, {v['text']}", num(v["truth"], 1), num(e["ols"]["bias"], 3), num(e["iv"]["bias"], 3),
                                num(e["gmm"]["bias"], 3), num(e["gmm"]["rej_lam1"], 2), num(e["gmm"]["rej_lam0"], 2),
                                num(e["gmm"]["coverage95"], 2), num(e["iv"]["coverage95"], 2), num(v["bootstrap_iv"]["coverage95"], 2),
                                num(v["J_rejection_5pct"], 2)]) + " \\\\")
    arows = []
    for tag, (sec, key, label) in _specs().items():
        r = app[sec]["specs"][key]
        arows.append(" & ".join([label, num(r["n"], 0), num(r["lam"], 3), ci(r["ci95"]), pval(r["p_lam1"]), pval(r["p_lam0"]),
                                 "--" if r["J_df"] == 0 else f"{num(r['J'], 1)} ({pval(r['J_p'])})"]) + " \\\\")
    cap = (f"Anchored unit-offset estimator. Top: {num(sim['reps'], 0)} simulated windows of {num(sim['hours'], 0)} hours per scenario, "
           "calibrated to the Bitfinex stress window; $\\lambda$ is the unit share of the offset. Bias is the mean error of OLS, "
           "IV (one instrument) and two-anchor GMM. Rejection rates are 5\\% Wald tests of $\\lambda=1$ and $\\lambda=0$; coverage is "
           "by the HAC interval of GMM and IV and the block-bootstrap interval of IV; $J$ rejects the over-identifying test "
           "(two anchors, three instruments, 5 df). Bottom: GMM estimates with HAC intervals, Wald $p$-values and Hansen's $J$ "
           "(statistic, $p$); df $=Km-1$ for $K$ anchors and $m$ instruments (3, 0, 3, 1, 3 and 3 in the rows below, in order; "
           "the ETH-only row is just identified). Samples differ by window and instrument availability.")
    return f"""{HEADER}
\\begin{{table*}}[!tp]
\\footnotesize
\\caption{{{cap}}}
\\label{{tab:theory}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lrrrrrrrrrr@{{}}}}
\\toprule
Scenario & $\\lambda$ & Bias OLS & Bias IV & Bias GMM & Rej.\\ $\\lambda{{=}}1$ & Rej.\\ $\\lambda{{=}}0$ & Cov.\\ GMM & Cov.\\ IV & Cov.\\ boot & $J$ rej. \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}

\\vspace{{4pt}}
\\begin{{tabular}}{{@{{}}lrrlrrr@{{}}}}
\\toprule
Sample & Hours & $\\hat\\lambda$ & 95\\% CI & $p(\\lambda{{=}}1)$ & $p(\\lambda{{=}}0)$ & $J$ ($p$) \\\\
\\midrule
{chr(10).join(arows)}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    for path, text in ((NUMBERS, numbers()), (TABLE, table())):
        path.write_text(text)
        print(f"WROTE {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
