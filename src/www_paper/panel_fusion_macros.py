"""Macros and table for the fusion panel (official versus anchor-corrected conversion), from reports/panel_fusion/results.json.

Writes paper/generated/panel_fusion_numbers.tex (macros ``\\NumPF...``, letters only, each with a source comment) and
panel_fusion_table.tex. Source: ``uv run python -m www_panel_fusion.run``. Run: ``uv run python -m www_paper.panel_fusion_macros``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "panel_fusion_numbers.tex"
TABLE = GEN / "panel_fusion_table.tex"
REPORT = ROOT / "reports/panel_fusion/results.json"
HEADER = "% generated by www_paper.panel_fusion_macros; do not edit"
SRC = "reports/panel_fusion/results.json"
MINUS = "\\ensuremath{-}"
UNITS = (("binance-BRL", "Brl", "Binance BRL"), ("binance-RUB", "Rub", "Binance RUB"), ("binance-TRY", "Try", "Binance TRY"),
         ("binance-ZAR", "Zar", "Binance ZAR"), ("bithumb-KRW", "Bithumb", "Bithumb KRW"), ("upbit-KRW", "Upbit", "Upbit KRW"))


def _load() -> Any:
    return json.loads(REPORT.read_text())


def f(v: float, d: int = 3) -> str:
    s = f"{v:.{d}f}"
    return s.replace("-", MINUS) if s.startswith("-") else s


def n(v: int) -> str:
    return f"{v:,}"


def yn(b: bool) -> str:
    return "yes" if b else "no"


def numbers() -> str:
    r = _load()
    out = [HEADER]

    def add(name: str, val: str, src: str) -> None:
        out.append(f"\\newcommand{{\\NumPF{name}}}{{{val}}} % {SRC} {src}")

    p = r["primary"]
    add("PrimMean", f(p["mean"]), "primary/mean")
    add("PrimLo", f(p["lo"]), "primary/lo")
    add("PrimHi", f(p["hi"]), "primary/hi")
    add("PrimHours", n(p["n_hours"]), "primary/n_hours")
    add("PrimDays", n(p["n_days"]), "primary/n_days")
    add("PrimSuccess", yn(p["success"]), "primary/success")
    add("Units", str(r["sample"]["n_units"]), "sample/n_units")
    add("PooledRatio", f(r["pooled_mae_ratio_A_over_O"]), "pooled_mae_ratio_A_over_O")
    add("MedianRatio", f(r["median_unit_mae_ratio_A_over_O"]), "median_unit_mae_ratio_A_over_O")
    for m in ("O", "A"):
        add(f"Mae{m}", f(p[m]["mae"], 1), f"primary/{m}/mae")
        add(f"Pnf{m}", f(p[m]["p95"], 1), f"primary/{m}/p95")
        add(f"Big{m}", n(p[m]["hours_ge_50"]), f"primary/{m}/hours_ge_50")
        add(f"Bias{m}", f(p[m]["mean_signed"], 1), f"primary/{m}/mean_signed")
        add(f"MedMae{m}", f(r["median_unit_mae"][m], 1), f"median_unit_mae/{m}")
    for unit, tag, _ in UNITS:
        u = r["units"][unit]
        d = u["log_error_diff"]
        add(f"{tag}Hours", n(d["n_hours"]), f"units/{unit}/log_error_diff/n_hours")
        add(f"{tag}MaeO", f(u["O"]["mae"], 1), f"units/{unit}/O/mae")
        add(f"{tag}MaeA", f(u["A"]["mae"], 1), f"units/{unit}/A/mae")
        add(f"{tag}Ratio", f(u["mae_ratio_A_over_O"]), f"units/{unit}/mae_ratio_A_over_O")
        add(f"{tag}Lo", f(d["lo"]), f"units/{unit}/log_error_diff/lo")
        add(f"{tag}Hi", f(d["hi"]), f"units/{unit}/log_error_diff/hi")
        add(f"{tag}Success", yn(d["success"]), f"units/{unit}/log_error_diff/success")
    add("UnitsSuccess", str(sum(u["log_error_diff"]["success"] for u in r["units"].values())), "units/*/log_error_diff/success (count)")
    fu = r["fused"]
    d = fu["log_error_diff_MA_vs_MO"]
    add("FusHours", n(fu["n_hours"]), "fused/n_hours")
    add("FusMean", f(d["mean"]), "fused/log_error_diff_MA_vs_MO/mean")
    add("FusLo", f(d["lo"]), "fused/log_error_diff_MA_vs_MO/lo")
    add("FusHi", f(d["hi"]), "fused/log_error_diff_MA_vs_MO/hi")
    add("FusSuccess", yn(d["success"]), "fused/log_error_diff_MA_vs_MO/success")
    for m in ("MO", "MA"):
        add(f"Fus{m}Mae", f(fu[m]["mae"], 1), f"fused/{m}/mae")
        add(f"Fus{m}Pnf", f(fu[m]["p95"], 1), f"fused/{m}/p95")
        add(f"Fus{m}Big", n(fu[m]["hours_ge_50"]), f"fused/{m}/hours_ge_50")
        add(f"Fus{m}Bias", f(fu[m]["mean_signed"], 1), f"fused/{m}/mean_signed")
    add("FusUnitsMean", f(fu["mean_units_per_hour"], 2), "fused/mean_units_per_hour")
    xs = r["x_source_hours"]
    tot = sum(xs.values())
    add("XBitstampShare", f(100 * xs["bitstamp"] / tot, 1), "x_source_hours/bitstamp (share, percent)")
    add("XBinanceUsShare", f(100 * xs["binance_us"] / tot, 1), "x_source_hours/binance_us (share, percent)")
    add("XKrakenHours", n(xs["kraken"]), "x_source_hours/kraken")
    return "\n".join(out) + "\n"


def table() -> str:
    r = _load()
    rows = []
    for unit, _, label in UNITS:
        u = r["units"][unit]
        rows.append(f"{label} & {f(u['O']['mae'], 1)} & {f(u['A']['mae'], 1)} & {f(u['mae_ratio_A_over_O'])} & {n(u['log_error_diff']['n_hours'])} \\\\")
    p = r["primary"]
    pooled = f"Pooled & {f(p['O']['mae'], 1)} & {f(p['A']['mae'], 1)} & {f(r['pooled_mae_ratio_A_over_O'])} & {n(p['n_hours'])} \\\\"
    med = f"Median of units & {f(r['median_unit_mae']['O'], 1)} & {f(r['median_unit_mae']['A'], 1)} & {f(r['median_unit_mae_ratio_A_over_O'])} & -- \\\\"
    body = "\n".join(rows)
    return f"""{HEADER}
\\begin{{table}}[t]
\\footnotesize
\\caption{{Dollar-price error of official versus anchor-corrected conversion (pre-registered). Mean absolute error in bps against Kraken BTC/USD hourly closes; O converts the local BTC price at the ECB reference rate, A converts through the venue's own USDT market and the external USDT/USD price. ARS, NGN and UAH are excluded because the ECB publishes no reference rate for them.}}
\\label{{tab:panelfusion}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lrrrr@{{}}}}
\\toprule
Unit & MAE O & MAE A & MAE ratio A/O & Hours \\\\
\\midrule
{body}
\\midrule
{pooled}
{med}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def main() -> int:
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())
    print(f"wrote {NUMBERS} and {TABLE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
