"""Macros and the benchmark table for the three locked fusion tests, parsed from autoresearch/final_*.log.

Writes paper/generated/bench_numbers.tex (macros ``\\NumB...``, each naming its source) and bench_table.tex.
Sources (each log is the single locked test run of a frozen method; parsed here, never re-run):
  autoresearch/final_test_*.log    UNIT-TD: share of the held-out mean-square gap removed on the test assets
  autoresearch/final_fuse_*.log    FUSE T1-T5: error of the fused USD price against Kraken, relative to the plain median
  autoresearch/final_stable_*.log  STABLE X1-X4: the same for stablecoin-quoted markets, relative to the naive median
  reports/unit_td/td_realdata.json CRH and GTM on the UNIT-TD test assets (post hoc; the locked log has no such rows)
Lines of a log that are not ``key: value`` (library warnings) are ignored. Run: ``uv run python -m www_paper.bench_macros``.
"""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "bench_numbers.tex"
TABLE = GEN / "bench_table.tex"
AUTO = ROOT / "autoresearch"
TD_REPORT = ROOT / "reports/unit_td/td_realdata.json"
HEADER = "% generated by www_paper.bench_macros; do not edit"
MINUS = "\\ensuremath{-}"

NUM = {"1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five"}
FUSE_EPS = ("T1", "T2", "T3", "T4", "T5")
STABLE_EPS = ("X1", "X2", "X3", "X4")
EP_LABEL = {"T1": "Bitfinex", "T2": "Binance.US", "T3": "FTX", "T4": "SVB", "T5": "calm",
            "X1": "USDC", "X2": "TUSD", "X3": "FDUSD", "X4": "calm"}
# (row label, UNIT-TD source, FUSE method key, STABLE method key); None means the method does not exist in that test
ROWS = [
    ("Plain median", "b2", "median", "B0"),
    ("Volume-weighted mean", None, "vwap", "B1"),
    ("Drop the most deviant source", None, "drop_deviant", None),
    ("Convert quote units, then median", None, None, "B2"),
    ("CRH", "crh", "crh", "B3"),
    ("GTM", "gtm", "gtm", None),
    ("Earlier unit-aware method (frozen)", None, "unit_aware", "B4"),
    ("Same-hour bitcoin gap", "b1", None, None),
    ("Method of this round", "est", "fuser", "fuser"),
]
ORACLE = ("Oracle (reference, not a method)", None, "oracle", "oracle")
WORD = {"median": "Median", "vwap": "Vwap", "drop_deviant": "DropDeviant", "crh": "Crh", "gtm": "Gtm",
        "unit_aware": "UnitAware", "fuser": "Fuser", "oracle": "Oracle", "trimmed": "Trimmed",
        "B0": "BZero", "B1": "BOne", "B2": "BTwo", "B3": "BThree", "B4": "BFour"}


def _one(pattern: str) -> Path:
    found = sorted(AUTO.glob(pattern))
    if len(found) != 1:
        raise FileNotFoundError(f"expected exactly one {pattern} in autoresearch/, found {len(found)}")
    return found[0]


def parse_log(path: Path) -> dict[str, str]:
    """``key: value`` lines only; the log mixes in library warnings, which have no such shape."""
    out: dict[str, str] = {}
    for line in path.read_text().splitlines():
        m = re.fullmatch(r"([A-Za-z0-9_\[\]]+): (\S.*)", line.strip())
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out


def sources() -> dict[str, tuple[Path, dict[str, str]]]:
    paths = {"Td": _one("final_test_*.log"), "Fuse": _one("final_fuse_*.log"), "Stable": _one("final_stable_*.log")}
    return {k: (p, parse_log(p)) for k, p in paths.items()}


def rel(log: dict[str, str], ep: str, method: str) -> float:
    return float(log[f"rel_e_{ep}_{method}"])


def td_post_hoc() -> dict[str, float]:
    pooled = json.loads(TD_REPORT.read_text())["part2"]["test"]["bootstrap"]["pooled"]
    return {m: float(pooled[m]["point"]) for m in ("crh", "gtm")}


def loop_counts(name: str) -> tuple[int, int]:
    """(runs, kept) in a committed loop log autoresearch/results_<name>_run1.tsv."""
    with (AUTO / f"results_{name}_run1.tsv").open() as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    return len(rows), sum(r["status"] == "keep" for r in rows)


def _num(v: float, d: int) -> str:
    s = f"{v:,.{d}f}"
    return MINUS + s[1:] if s.startswith("-") and s.strip("-0.,") else s.lstrip("-")


def macros() -> list[tuple[str, str, str]]:
    src = sources()
    out: list[tuple[str, str, str]] = []
    pt, td = src["Td"]
    rp = pt.relative_to(ROOT)
    for key, name in (("test_score", "TdTestScore"), ("b0_test", "TdBZero"), ("b1_test", "TdBOne"), ("b2_test", "TdBTwo")):
        out.append((f"NumB{name}", _num(float(td[key]), 3), f"{rp} {key}"))
    for m, v in td_post_hoc().items():
        out.append((f"NumBTd{WORD[m]}", _num(v, 3), f"{TD_REPORT.relative_to(ROOT)} part2/test/bootstrap/pooled/{m}/point"))
    for tag, name in (("Fuse", "fuse"), ("Stable", "stable")):
        runs, kept = loop_counts(name)
        out += [(f"NumB{tag}LoopRuns", str(runs), f"autoresearch/results_{name}_run1.tsv, rows"),
                (f"NumB{tag}LoopKept", str(kept), f"autoresearch/results_{name}_run1.tsv, rows with status keep")]
    for tag, eps, methods in (("Fuse", FUSE_EPS, ("fuser", "median", "vwap", "trimmed", "drop_deviant", "crh", "gtm",
                                                  "unit_aware", "oracle")),
                              ("Stable", STABLE_EPS, ("fuser", "B0", "B1", "B2", "B3", "B4", "oracle"))):
        path, log = src[tag]
        rp = path.relative_to(ROOT)
        out.append((f"NumB{tag}TestScore", _num(float(log["test_score"]), 3), f"{rp} test_score"))
        for ep in eps:
            for m in methods:
                out.append((f"NumB{tag}{'T' if ep[0] == 'T' else 'X'}{NUM[ep[1]]}{WORD[m]}", _num(rel(log, ep, m), 2),
                            f"{rp} rel_e_{ep}_{m}"))
    return out


def numbers() -> str:
    rows = macros()
    names = [r[0] for r in rows]
    assert len(names) == len(set(names)) and all(n.isalpha() for n in names), "macro names must be unique letters"
    return "\n".join([HEADER] + [f"\\newcommand{{\\{n}}}{{{v}}} % {s}" for n, v, s in rows]) + "\n"


def _cells() -> dict[tuple[int, str], tuple[float, str] | None]:
    """(row index, column) -> (value, formatted); columns are td, T1..T5, X1..X4."""
    src = sources()
    td = {"b1": float(src["Td"][1]["b1_test"]), "b2": float(src["Td"][1]["b2_test"]),
          "est": float(src["Td"][1]["test_score"]), **td_post_hoc()}
    cells: dict[tuple[int, str], tuple[float, str] | None] = {}
    for i, (_, t, f, s) in enumerate(ROWS + [ORACLE]):
        cells[(i, "td")] = None if t is None else (td[t], _num(td[t], 3) + ("$^\\dagger$" if t in ("crh", "gtm") else ""))
        for ep in FUSE_EPS:
            cells[(i, ep)] = None if f is None else (rel(src["Fuse"][1], ep, f), _num(rel(src["Fuse"][1], ep, f), 2))
        for ep in STABLE_EPS:
            cells[(i, ep)] = None if s is None else (rel(src["Stable"][1], ep, s), _num(rel(src["Stable"][1], ep, s), 2))
    return cells


def table() -> str:
    cells = _cells()
    n_methods = len(ROWS)
    cols = ["td", *FUSE_EPS, *STABLE_EPS]
    best: dict[str, float] = {}
    for c in cols:
        vals = [cells[(i, c)][0] for i in range(n_methods) if cells[(i, c)] is not None]
        best[c] = max(vals) if c == "td" else min(vals)

    def fmt(i: int, c: str) -> str:
        cell = cells[(i, c)]
        if cell is None:
            return "--"
        return f"\\textbf{{{cell[1]}}}" if i < n_methods and cell[0] == best[c] else cell[1]

    body = []
    for i, (label, *_rest) in enumerate(ROWS + [ORACLE]):
        if i == n_methods:
            body.append("\\midrule")
        body.append(f"{label} & " + " & ".join(fmt(i, c) for c in cols) + " \\\\")
    return (f"{HEADER}\n\\begin{{table*}}[t]\n\\footnotesize\n"
            "\\caption{The three locked fusion tests. Each method was frozen, then scored once on episodes it had never "
            "seen (T1 Oct 2018 to May 2019, T2 May to Jul 2023, T3 Nov 2022, T4 Mar 2023, T5 other 2022--23; X1 Mar 2023, X2 Jan 2024, X3 Apr 2025, X4 Dec 2023 and Feb--Mar 2025). UNIT-TD: share of the mean-square Bitfinex--Coinbase gap removed on five withheld assets (higher is better). "
            "FUSE (T1--T5) and STABLE (X1--X4): mean absolute error of the fused dollar price against a Kraken reference that "
            "never entered fusion, divided by the plain median's error on the same hours (below 1 beats the median; bold: best "
            "method in the column; for STABLE the plain median treats every stablecoin as one dollar). The oracle knows which "
            "sources are clean and is a reference point. In STABLE, X4 is a calm placebo on which the method's own check "
            "(at most 1.02) failed. $^\\dagger$ Post hoc: not in the locked log.}\n"
            "\\label{tab:bench}\n\\setlength{\\tabcolsep}{3.5pt}\n\\begin{tabular}{@{}lcccccccccc@{}}\n\\toprule\n"
            " & UNIT-TD & \\multicolumn{5}{c}{FUSE} & \\multicolumn{4}{c}{STABLE} \\\\\n"
            "\\cmidrule(lr){3-7}\\cmidrule(lr){8-11}\n"
            "Method & Held-out & " + " & ".join(f"{e}" for e in (*FUSE_EPS, *STABLE_EPS)) + " \\\\\n"
            "& \\scriptsize (share removed) & " + " & ".join(f"\\scriptsize {EP_LABEL[e]}" for e in (*FUSE_EPS, *STABLE_EPS))
            + " \\\\\n\\midrule\n" + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n")


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())
    print(f"WROTE {NUMBERS.relative_to(ROOT)} and {TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
