"""Render the paper's abstract as plain text for the submission form (macros expanded, LaTeX removed).

Writes docs/review/ABSTRACT_SUBMISSION.md. Run: ``uv run python -m www_paper.abstract_text``.
The human author submits; nothing here is sent anywhere.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAIN = ROOT / "paper/main.tex"
MACRO_FILES = [ROOT / "paper/generated/numbers.tex", ROOT / "paper/generated/rescue_numbers.tex",
               ROOT / "paper/generated/unit_numbers.tex", ROOT / "paper/generated/posthoc_numbers.tex",
               ROOT / "paper/generated/sweep_numbers.tex", ROOT / "paper/generated/noise_numbers.tex",
               ROOT / "paper/generated/anchor_ext_numbers.tex", ROOT / "paper/generated/robust_numbers.tex",
               ROOT / "paper/generated/td_numbers.tex", ROOT / "paper/generated/bench_numbers.tex",
               ROOT / "paper/generated/theory_numbers.tex", ROOT / "paper/generated/robust_anchor_numbers.tex",
               ROOT / "paper/generated/kimchi_numbers.tex"]
OUTPUT = ROOT / "docs/review/ABSTRACT_SUBMISSION.md"


def macros() -> dict[str, str]:
    out: dict[str, str] = {}
    for f in MACRO_FILES:
        for name, value in re.findall(r"\\newcommand\{\\(\w+)\}\{([^}]*)\}", f.read_text()):
            out[name] = value
    return out


def plain(tex: str, table: dict[str, str]) -> str:
    text = re.sub(r"\\(Num\w+)\{\}", lambda m: table[m.group(1)], tex)
    text = re.sub(r"\\(Num[A-Za-z]+)", lambda m: table[m.group(1)], text)
    text = text.replace("\\%", "%").replace("``", "\u201c").replace("''", "\u201d").replace("--", "\u2013")
    text = re.sub(r"\\emph\{([^}]*)\}", r"\1", text)
    text = re.sub(r"~", " ", text)
    if "\\" in text or "{" in text:
        raise ValueError(f"unconverted LaTeX left in abstract: {text[:200]}")
    return " ".join(text.split())


def title(tex: str) -> str:
    return re.search(r"\\title\{([^}]*)\}", tex).group(1)


def build() -> str:
    tex = MAIN.read_text()
    body = tex.split("\\begin{abstract}", 1)[1].split("\\end{abstract}", 1)[0]
    abstract = plain(body, macros())
    words = len(abstract.split())
    return (
        "# Abstract for the WWW 2027 abstract registration (due 2026-10-18 AoE)\n\n"
        "<!-- generated by www_paper.abstract_text from paper/main.tex; do not edit -->\n\n"
        "The human author submits this; it has not been sent anywhere. Track: Web Economics and Digital Society. "
        "Double-blind: do not add names, affiliations or repository links.\n\n"
        f"**Title:** {title(tex)}\n\n"
        f"**Abstract ({words} words):**\n\n{abstract}\n\n"
        "**Suggested keywords:** exchange dollars; unit of account; truth discovery; price feeds and oracles; "
        "Web data quality; cryptocurrency markets; reproducibility\n"
    )


def main() -> None:
    OUTPUT.write_text(build())
    print(f"WROTE {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
