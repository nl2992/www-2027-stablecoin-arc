"""Macros for the EXPLORATORY placebo and comparator-C analyses (not pre-registered).

Writes paper/generated/explore_numbers.tex (macros ``\\NumEX...``, letters only, each with a source comment) from
reports/explore/placebo.json and reports/explore/comparator.json. Run: ``uv run python -m www_paper.explore_macros``.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NUMBERS = ROOT / "paper/generated/explore_numbers.tex"
PLACEBO = ROOT / "reports/explore/placebo.json"
COMPARATOR = ROOT / "reports/explore/comparator.json"
HEADER = "% generated by www_paper.explore_macros; EXPLORATORY analyses, not pre-registered; do not edit"
MINUS = "\\ensuremath{-}"


def f(v: float, d: int = 3) -> str:
    s = f"{v:.{d}f}"
    return s.replace("-", MINUS) if s.startswith("-") else s


def numbers() -> str:
    pl, cp = json.loads(PLACEBO.read_text()), json.loads(COMPARATOR.read_text())
    out = [HEADER]

    def add(name: str, val: str, src: str, rep: str) -> None:
        out.append(f"\\newcommand{{\\NumEX{name}}}{{{val}}} % reports/explore/{rep}.json {src}")

    for key, tag in (("stress_F_hours", "PlaceboStress"), ("all_included_hours", "PlaceboAll")):
        m = pl["mismatched_currency"][key]
        iv = m["pooled"]["iv"]
        add(f"{tag}PooledLam", f(iv["lam"]), f"mismatched_currency/{key}/pooled/iv/lam", "placebo")
        add(f"{tag}PooledLo", f(iv["lo"]), f"mismatched_currency/{key}/pooled/iv/lo", "placebo")
        add(f"{tag}PooledHi", f(iv["hi"]), f"mismatched_currency/{key}/pooled/iv/hi", "placebo")
        add(f"{tag}PooledOls", f(m["pooled"]["ols"]["lam"]), f"mismatched_currency/{key}/pooled/ols/lam", "placebo")
        add(f"{tag}Pairs", str(m["n_pairs"]), f"mismatched_currency/{key}/n_pairs", "placebo")
        for k, nm in (("median_pair_iv", "Median"), ("min_pair_iv", "Min"), ("max_pair_iv", "Max")):
            add(f"{tag}Pair{nm}", f(m["summary"][k]), f"mismatched_currency/{key}/summary/{k}", "placebo")
        add(f"{tag}PairsExcludeZero", str(m["summary"]["n_ci_excludes_0"]), f"mismatched_currency/{key}/summary/n_ci_excludes_0", "placebo")
        add(f"{tag}PairsIncludeOne", str(m["summary"]["n_ci_includes_1"]), f"mismatched_currency/{key}/summary/n_ci_includes_1", "placebo")
    for pair, v in pl["mismatched_currency"]["stress_F_hours"]["pairs"].items():
        t = pair.replace(">", "To")
        for k in ("lam", "lo", "hi"):
            add(f"Pair{t}{k.title()}", f(v["iv"][k]), f"mismatched_currency/stress_F_hours/pairs/{pair}/iv/{k}", "placebo")
    for key, tag in (("primary_2022_calm", "CalmPrimary"), ("extended_2022_2023_calm", "CalmExtended")):
        c = pl["calm_cross_venue"][key]
        add(f"{tag}Lam", f(c["ols"]["lam"]), f"calm_cross_venue/{key}/ols/lam", "placebo")
        add(f"{tag}Lo", f(c["ols"]["lo"]), f"calm_cross_venue/{key}/ols/lo", "placebo")
        add(f"{tag}Hi", f(c["ols"]["hi"]), f"calm_cross_venue/{key}/ols/hi", "placebo")
        add(f"{tag}VarL", f(c["var_L_within_day_bps2"], 1), f"calm_cross_venue/{key}/var_L_within_day_bps2", "placebo")
        add(f"{tag}Hours", f"{c['n_hours']:,}", f"calm_cross_venue/{key}/n_hours", "placebo")
        add(f"{tag}Days", str(c["n_days"]), f"calm_cross_venue/{key}/n_days", "placebo")
    p = cp["pooled"]
    add("CompHours", f"{p['n_hours']:,}", "pooled/n_hours", "comparator")
    for k in "OAC":
        add(f"CompMae{k}", f(p["mae"][k], 2), f"pooled/mae/{k}", "comparator")
    for k, nm in (("logdiff_A_minus_C", "AC"), ("logdiff_C_minus_O", "CO")):
        add(f"Comp{nm}Mean", f(p[k]["mean"]), f"pooled/{k}/mean", "comparator")
        add(f"Comp{nm}Lo", f(p[k]["lo"]), f"pooled/{k}/lo", "comparator")
        add(f"Comp{nm}Hi", f(p[k]["hi"]), f"pooled/{k}/hi", "comparator")
    add("CompRatioAC", f(p["mae_ratio_A_over_C"]), "pooled/mae_ratio_A_over_C", "comparator")
    for unit, u in cp["units"].items():
        t = "".join(w.title() for w in unit.split("-"))
        for k in "OAC":
            add(f"Unit{t}Mae{k}", f(u["mae"][k], 2), f"units/{unit}/mae/{k}", "comparator")
        for k, nm in (("logdiff_A_minus_C", "AC"), ("logdiff_C_minus_O", "CO")):
            for q in ("mean", "lo", "hi"):
                add(f"Unit{t}{nm}{q.title()}", f(u[k][q]), f"units/{unit}/{k}/{q}", "comparator")
    return "\n".join(out) + "\n"


def main() -> int:
    NUMBERS.write_text(numbers())
    print(f"wrote {NUMBERS}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
