"""Macros and table for the Kraken fiat-panel slice, from reports/panel_kraken/results.json.

Writes paper/generated/panel_kraken_numbers.tex (macros ``\\NumPK...``, letters only, each with a source comment) and
panel_kraken_table.tex. Source: ``uv run python -m www_panel_kraken.run``. Run: ``uv run python -m www_paper.panel_kraken_macros``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "panel_kraken_numbers.tex"
TABLE = GEN / "panel_kraken_table.tex"
REPORT = ROOT / "reports/panel_kraken/results.json"
HEADER = "% generated by www_paper.panel_kraken_macros; do not edit"
SRC = "reports/panel_kraken/results.json"
MINUS = "\\ensuremath{-}"


def _load() -> Any:
    return json.loads(REPORT.read_text())


def f(v: float, d: int = 3) -> str:
    s = f"{v:.{d}f}"
    return s.replace("-", MINUS) if s.startswith("-") else s


def _tag(cur: str) -> str:
    return cur[0] + cur[1:].lower()


def yn(b: bool) -> str:
    return "yes" if b else "no"


def numbers() -> str:
    r = _load()
    out = [HEADER]

    def add(name: str, val: str, src: str) -> None:
        out.append(f"\\newcommand{{\\NumPK{name}}}{{{val}}} % {SRC} {src}")

    for key, tag in (("pooled_stress", "Stress"), ("pooled_calm", "Calm"), ("pooled_all", "All")):
        e = r[key]
        if "iv" not in e:
            continue
        add(f"Pooled{tag}Lam", f(e["iv"]["lam"]), f"{key}/iv/lam")
        add(f"Pooled{tag}Lo", f(e["iv"]["lo"]), f"{key}/iv/lo")
        add(f"Pooled{tag}Hi", f(e["iv"]["hi"]), f"{key}/iv/hi")
        add(f"Pooled{tag}Ols", f(e["ols"]["lam"]), f"{key}/ols/lam")
        add(f"Pooled{tag}Days", f"{e['n_days']:,}", f"{key}/n_days")
        add(f"Pooled{tag}Hours", f"{e['n_hours']:,}", f"{key}/n_hours")
    add("CurrencyCount", str(len(r["by_currency"])), "by_currency (count)")
    for cur, c in r["by_currency"].items():
        t = _tag(cur)
        add(f"{t}StressMonths", str(c["stress_months"]), f"by_currency/{cur}/stress_months")
        add(f"{t}CalmMonths", str(c["calm_months"]), f"by_currency/{cur}/calm_months")
        add(f"{t}AllLam", f(c["all"]["iv"]["lam"]), f"by_currency/{cur}/all/iv/lam")
        add(f"{t}AllLo", f(c["all"]["iv"]["lo"]), f"by_currency/{cur}/all/iv/lo")
        add(f"{t}AllHi", f(c["all"]["iv"]["hi"]), f"by_currency/{cur}/all/iv/hi")
        if "stress" in c:
            add(f"{t}Lam", f(c["stress"]["iv"]["lam"]), f"by_currency/{cur}/stress/iv/lam")
            add(f"{t}Lo", f(c["stress"]["iv"]["lo"]), f"by_currency/{cur}/stress/iv/lo")
            add(f"{t}Hi", f(c["stress"]["iv"]["hi"]), f"by_currency/{cur}/stress/iv/hi")
    add("StressUnitMonths", str(sum(c["stress_months"] for c in r["by_currency"].values())), "by_currency/*/stress_months (sum)")
    add("CalmUnitMonths", str(sum(c["calm_months"] for c in r["by_currency"].values())), "by_currency/*/calm_months (sum)")
    k1, k2 = r["K1"], r["K2"]
    add("KOnePass", yn(k1["pass"]), "K1/pass")
    add("KOneAllExcludesZero", yn(k1["all_months"]["excludes_0"]), "K1/all_months/excludes_0")
    add("KTwoPass", yn(k2["pass"]), "K2/pass")
    add("KTwoInside", str(k2["n_inside"]), "K2/n_inside")
    add("KTwoEligible", str(k2["n_eligible"]), "K2/n_eligible")
    add("KTwoAllPass", yn(k2["all_months"]["pass"]), "K2/all_months/pass")
    add("KTwoAllInside", str(k2["all_months"]["n_inside"]), "K2/all_months/n_inside")
    add("KTwoAllEligible", str(k2["all_months"]["n_eligible"]), "K2/all_months/n_eligible")
    return "\n".join(out) + "\n"


def table() -> str:
    r = _load()
    rows = []
    for cur, c in r["by_currency"].items():
        e = c["all"]["iv"]
        k2s = "--"
        if "stress" in c:
            s = c["stress"]["iv"]
            k2s = f"{f(s['lam'])} [{f(s['lo'])}, {f(s['hi'])}]"
        rows.append(f"{cur} & {c['stress_months']} & {c['calm_months']} & {k2s} & {f(e['lam'])} [{f(e['lo'])}, {f(e['hi'])}] \\\\")
    ps, pa = r["pooled_stress"].get("iv"), r["pooled_all"]["iv"]
    pst = f"{f(ps['lam'])} [{f(ps['lo'])}, {f(ps['hi'])}]" if ps else "--"
    pooled = (f"Pooled & {sum(c['stress_months'] for c in r['by_currency'].values())} & "
              f"{sum(c['calm_months'] for c in r['by_currency'].values())} & {pst} & {f(pa['lam'])} [{f(pa['lo'])}, {f(pa['hi'])}] \\\\")
    body = "\n".join(rows)
    k1, k2 = ("pass" if r["K1"]["pass"] else "fail"), ("pass" if r["K2"]["pass"] else "fail")
    return f"""{HEADER}
\\begin{{table}}[t]
\\footnotesize
\\caption{{Kraken fiat-market slice (pre-registered). Hourly Kraken XBT, ETH and USDT markets in the freely convertible currencies shown; $(D-X)$ on $L$ with day fixed effects, IV with the ETH gap as instrument, $L$ measured against Bitstamp BTC/USD and $X$ Kraken USDT/USD. Months are classified stress or calm from $L$ alone. Cells give $\\hat\\lambda$ with a 95\\% 7-day moving-block bootstrap interval, for stress months and for all months. Pre-registered outcomes: K1 {k1}, K2 {k2}.}}
\\label{{tab:panelkraken}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lrrll@{{}}}}
\\toprule
Currency & Stress & Calm & $\\hat\\lambda$ stress (95\\% CI) & $\\hat\\lambda$ all (95\\% CI) \\\\
\\midrule
{body}
\\midrule
{pooled}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def main() -> int:
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())
    print(f"wrote {NUMBERS} and {TABLE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
