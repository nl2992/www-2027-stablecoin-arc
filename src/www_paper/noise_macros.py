"""Macros and table for the noise-bound analysis, from reports/unit_td/noise_bounds.json and configs/fee_schedule.json.

Writes paper/generated/noise_numbers.tex (macros ``\\NumN...``, each with a source comment) and noise_table.tex.
Source: ``uv run python -m www_auto.noise_bounds``. Run: ``uv run python -m www_paper.noise_macros``.
Calm years are 2020-2023 (2019 is the Bitfinex stress year, 2017-2018 are the early-market years).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "noise_numbers.tex"
TABLE = GEN / "noise_table.tex"
BOUNDS = ROOT / "reports/unit_td/noise_bounds.json"
FEES = ROOT / "configs/fee_schedule.json"
HEADER = "% generated by www_paper.noise_macros; do not edit"
PAIRS = (("bitfinex-bitstamp", "Bitfinex--Bitstamp", "BfxBst"), ("bitfinex-coinbase", "Bitfinex--Coinbase", "BfxCb"),
         ("coinbase-bitstamp", "Coinbase--Bitstamp", "CbBst"))
YEARS = tuple(range(2017, 2024))
CALM = tuple(range(2020, 2024))
MINUS = "\\ensuremath{-}"
SRC = "reports/unit_td/noise_bounds.json"


def _load(path: Path) -> Any:
    return json.loads(path.read_text())


def _num(v: float, d: int) -> str:
    s = f"{v:,.{d}f}"
    if s.startswith("-"):
        return s[1:] if not s.strip("-0.,") else MINUS + s[1:]
    return s


def _cell(v: float | None, d: int = 2) -> str:
    return "--" if v is None else _num(v, d)


def _vals(b: dict, key: str, years=CALM, fn=lambda r: None) -> list[float]:
    out = []
    for y in years:
        v = fn(b["pairs"][key][str(y)])
        if v is not None:
            out.append(v)
    return out


def _tick_bps(b: dict, pair: str, asset: str, year: int) -> float | None:
    vals = []
    for venue in pair.split("-"):
        t = b["ticks"][f"{venue}|{asset}"][str(year)]
        if t is not None:
            vals.append(t["tick_bps"])
    return max(vals) if vals else None


def macros() -> list[tuple[str, str, str]]:
    b, fees = _load(BOUNDS), _load(FEES)
    out: list[tuple[str, str, str]] = []

    def rng(name: str, key: str, fn, src: str, d: int, years=CALM) -> None:
        v = _vals(b, key, years, fn)
        out.append((f"{name}Min", _num(min(v), d), f"{SRC} {src} min over {years[0]}-{years[-1]}"))
        out.append((f"{name}Max", _num(max(v), d), f"{SRC} {src} max over {years[0]}-{years[-1]}"))

    bands = [b["pairs"][k][str(y)]["band_bps"] for k, _, _ in PAIRS for y in YEARS]
    out.append(("NumNBandMin", _num(min(bands), 0), f"{SRC} pairs/*/*/band_bps min over pair-years (sum of two base-tier taker fees)"))
    out.append(("NumNBandMax", _num(max(bands), 0), f"{SRC} pairs/*/*/band_bps max over pair-years"))
    for key, _, tag in PAIRS:
        rng(f"NumN{tag}ShareBtcPct", key, lambda r: 100 * r["share_above_band_btc"], "share_above_band_btc, percent", 2)
        rng(f"NumN{tag}AcOne", key, lambda r: r["daily_ac"]["1"], "daily_ac/1", 2)
        rng(f"NumN{tag}AcSeven", key, lambda r: r["daily_ac"]["7"], "daily_ac/7", 2)
        rng(f"NumN{tag}AcThirty", key, lambda r: r["daily_ac"]["30"], "daily_ac/30", 2)
        rng(f"NumN{tag}CommonDaily", key, lambda r: r["common_share"]["daily_centered"], "common_share/daily_centered", 2)
        rng(f"NumN{tag}CommonHourly", key, lambda r: r["common_share"]["hourly_centered"], "common_share/hourly_centered", 2)
        for conv, cname in (("median", "Med"), ("last", "Last"), ("sync", "Sync")):
            rng(f"NumN{tag}Expl{cname}", key, lambda r, c=conv: r["timing"][c]["explained_share"], f"timing/{conv}/explained_share", 2)
        rng(f"NumN{tag}GapBtc", key, lambda r: r["median_abs_gap_btc_bps"], "median_abs_gap_btc_bps", 1)
    calm_max = max(max(_vals(b, k, CALM, lambda r, a=a: 100 * r[f"share_above_band_{a}"])) for k, _, _ in PAIRS for a in ("btc", "eth"))
    out.append(("NumNCalmAboveBandMaxPct", _num(calm_max, 2), f"{SRC} share_above_band_{{btc,eth}} max over pairs and 2020-2023, percent"))
    for asset in ("BTC", "ETH"):
        t = [_tick_bps(b, k, asset, y) for k, _, _ in PAIRS for y in CALM]
        t = [x for x in t if x is not None]
        out.append((f"NumNTick{asset.title()}CalmMax", _num(max(t), 2), f"{SRC} ticks/*|{asset}/2020-2023 tick_bps, max over venues and years"))
    for key, _, tag in PAIRS:
        for name, (m, _) in zip(("Calm", "Stress"), (("calm_2022-06", 0), ("stress_2019-03", 0))):
            ll = b["leadlag"][key][m]
            out.append((f"NumN{tag}Lag{name}Levels", _num(ll["levels"]["peak_lag_min"], 0), f"{SRC} leadlag/{key}/{m}/levels/peak_lag_min"))
            out.append((f"NumN{tag}Lag{name}Changes", _num(ll["changes"]["peak_lag_min"], 0), f"{SRC} leadlag/{key}/{m}/changes/peak_lag_min"))
    zero = sum(ll[v]["peak_lag_min"] == 0 for k in b["leadlag"].values() for ll in k.values() for v in ("levels", "changes"))
    total = sum(1 for k in b["leadlag"].values() for ll in k.values() for _ in ("levels", "changes"))
    out.append(("NumNLagZeroCount", str(zero), f"{SRC} leadlag peak lags equal to zero"))
    out.append(("NumNLagTotal", str(total), f"{SRC} leadlag series examined (3 pairs x 2 months x levels/changes)"))
    n_ver = {s: sum(e["status"] == s for v in fees["venues"].values() for e in v) for s in ("secondary", "inferred", "unverified")}
    for s, n in n_ver.items():
        out.append((f"NumNFee{s.title()}", str(n), f"configs/fee_schedule.json entries with status {s}"))
    return out


def numbers() -> str:
    lines = [HEADER]
    for name, val, src in macros():
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}} % {src}")
    return "\n".join(lines) + "\n"


def table() -> str:
    b = _load(BOUNDS)
    rows = []
    for key, label, _ in PAIRS:
        rows.append("\\midrule")
        for y in YEARS:
            r = b["pairs"][key][str(y)]
            t = r["timing"]
            tb, te = _tick_bps(b, key, "BTC", y), _tick_bps(b, key, "ETH", y)
            share = 100 * r["share_above_band_btc"] if r["share_above_band_btc"] is not None else None
            rows.append(" & ".join([f"{label if y == YEARS[0] else ''} {y}".strip(), _cell(r["band_bps"], 0),
                                    f"{_cell(tb, 2)} / {_cell(te, 2)}", _cell(r["median_abs_gap_btc_bps"], 1), _cell(share, 1),
                                    _cell(r["daily_ac"]["1"], 2), _cell(t["median"]["explained_share"], 2),
                                    _cell(t["last"]["explained_share"], 2), _cell(t["sync"]["explained_share"], 2)]) + " \\\\")
    body = "\n".join(rows).replace("\\midrule\n", "\\midrule\n", 1)
    return f"""{HEADER}
\\begin{{table*}}[t]
\\footnotesize
\\caption{{Noise bounds on the pair gaps. Band: sum of the two venues' base-tier taker fees (bps; hour-weighted within a year; \\texttt{{configs/fee\\_schedule.json}}). Tick: the smallest recurring minute-to-minute price change in bps of the median close, larger of the two venues, BTC / ETH. $|L|$: median absolute hourly BTC gap (bps). $>$Band: share of hours (percent) with the BTC gap beyond the band. AC(1): first-order autocorrelation of the daily cross-asset gap (mean of the BTC and ETH daily-median gaps). Agreement: explained share $1-\\overline{{(g_{{ETH}}-g_{{BTC}})^2}}/\\overline{{g_{{ETH}}^2}}$ of the hourly ETH gap by the BTC gap, with hourly medians of traded minutes (Med), the last traded close (Last), or only hours in which all four legs traded in the final minute (Sync).}}
\\label{{tab:noise}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lrrrrrrrr@{{}}}}
\\toprule
Pair, year & Band & Tick & $|L|$ & $>$Band & AC(1) & Med & Last & Sync \\\\
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())
    print(f"WROTE {NUMBERS} {TABLE}")


if __name__ == "__main__":
    main()
