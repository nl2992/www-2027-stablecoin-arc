"""Macros and table from reports/unit_td/robust_eval.json (``uv run python -m www_auto.robust_eval``).

Writes paper/generated/robust_numbers.tex (macro prefix NumR) and paper/generated/robust_eval_table.tex.
Run: ``uv run python -m www_paper.robust_macros``.
"""

from __future__ import annotations

import json
from typing import Any

from .unit_macros import GEN, ROOT, _num

ROBUST = ROOT / "reports/unit_td/robust_eval.json"
NUMBERS = GEN / "robust_numbers.tex"
TABLE = GEN / "robust_eval_table.tex"
SRC = "reports/unit_td/robust_eval.json"
HEADER = "% generated by www_paper.robust_macros; do not edit"
PWORD = {"2017-2019": "PeriodOne", "2020-2023": "PeriodTwo"}
BWORD = {"week": "Week", "month": "Month", "quarter": "Quarter"}
MWORD = {"b1": "BOne", "b2": "BTwo", "est": "Est", "diff": "Diff"}
SPLIT = {"test": "Test", "dev": "Dev", "control": "Ctrl"}
YWORD = {"2017": "TwentySeventeen", "2018": "TwentyEighteen", "2019": "TwentyNineteen", "2020": "TwentyTwenty",
         "2021": "TwentyTwentyOne", "2022": "TwentyTwentyTwo", "2023": "TwentyTwentyThree"}
CWORD = {"1.0": "One", "0.5": "Half", "0.25": "Quarter", "0.0": "Zero"}


def load() -> dict[str, Any]:
    return json.loads(ROBUST.read_text())


def _s(v: float, d: int = 3) -> str:
    return _num(v, d)


def _ci(prefix: str, st: dict[str, float], where: str) -> list[tuple[str, str, str]]:
    return [(prefix, _s(st["point"]), where), (prefix + "Lo", _s(st["lo"]), where + " (95% lower)"),
            (prefix + "Hi", _s(st["hi"]), where + " (95% upper)")]


def numbers() -> str:
    d = load()
    rows: list[tuple[str, str, str]] = []
    rows.append(("NumRBootDraws", str(d["bootstrap"]["draws"]), f"{SRC} bootstrap/draws"))
    for p, splits in d["periods"].items():
        for s, r in splits.items():
            base = f"NumR{PWORD[p]}{SPLIT[s]}"
            rows.append((base + "Hours", f"{r['n_hours']:,}", f"{SRC} periods/{p}/{s}/n_hours"))
            if r["n_hours"] == 0:
                continue
            for m in ("b1", "b2", "est"):
                rows.append((base + MWORD[m], _s(r[m]), f"{SRC} periods/{p}/{s}/{m}"))
            rows.append((base + "Diff", _s(r["diff_est_minus_b2"]), f"{SRC} periods/{p}/{s}/diff_est_minus_b2"))
            rows += _ci(base + "EstMonth", r["month_block_ci"]["est"], f"{SRC} periods/{p}/{s}/month_block_ci/est")
    h = d["honest"]
    rows.append(("NumRHonestChosen", _num(h["chosen_constant"], 2), f"{SRC} honest/chosen_constant"))
    rows.append(("NumRFrozenConst", _num(h["frozen_constant"], 2), f"{SRC} honest/frozen_constant"))
    for c, v in h["selection_dev_scores"].items():
        rows.append((f"NumRHonestDev{CWORD[c]}", _s(v["dev_2017_2019"]), f"{SRC} honest/selection_dev_scores/{c}/dev_2017_2019"))
    for s, r in h["score_2020_2023"].items():
        for m in ("b1", "b2", "est"):
            rows.append((f"NumRHonest{SPLIT[s]}{MWORD[m]}", _s(r[m]), f"{SRC} honest/score_2020_2023/{s}/{m}"))
    for b, bl in d["blocks"].items():
        w = BWORD[b]
        rows.append((f"NumR{w}NBlocks", str(bl["test"]["n_blocks"]), f"{SRC} blocks/{b}/test/n_blocks"))
        for s in ("test", "control"):
            for g, ms in bl[s].items():
                if g == "n_blocks":
                    continue
                label = "Pooled" if g == "pooled" else g.split(":")[1]
                for m in ("est", "diff") if g == "pooled" else ("est",):
                    rows += _ci(f"NumR{w}{SPLIT[s]}{label}{MWORD[m]}", ms[m], f"{SRC} blocks/{b}/{s}/{g}/{m}")
    for b in ("month", "quarter"):
        rows.append((f"NumRWiden{BWORD[b]}Median", f"{d['widening']['median_ratio_vs_week'][b]:.2f}",
                     f"{SRC} widening/median_ratio_vs_week/{b}"))
        for k in ("test_pooled_est", "test_pooled_diff", "control_pooled_est", "control_pooled_diff"):
            rows.append(("NumRWiden" + BWORD[b] + "".join(x.capitalize() for x in k.split("_")),
                         f"{d['widening'][k]['ratio_vs_week'][b]:.2f}", f"{SRC} widening/{k}/ratio_vs_week/{b}"))
    for s in ("test", "dev"):
        for m in ("est", "b2"):
            x = d["medians"][s][m]
            for kind, word in (("by_asset", "Asset"), ("by_year", "Year"), ("by_asset_year", "Cell")):
                for stat in ("median", "min", "max"):
                    rows.append((f"NumRMed{SPLIT[s]}{MWORD[m]}{word}{stat.capitalize()}", _s(x[kind][stat]),
                                 f"{SRC} medians/{s}/{m}/{kind}/{stat}"))
            rows.append((f"NumRMed{SPLIT[s]}{MWORD[m]}Pooled", _s(x["pooled"]), f"{SRC} medians/{s}/{m}/pooled"))
    names = [r[0] for r in rows]
    assert len(names) == len(set(names)) and all(n.isalpha() for n in names), "macro names must be unique letters"
    body = "\n".join(f"\\newcommand{{\\{n}}}{{{v}}} % {s}" for n, v, s in rows)
    return f"{HEADER}\n{body}\n"


def _f(st: dict[str, float]) -> str:
    return f"{_s(st['point'])} [{_s(st['lo'])}, {_s(st['hi'])}]"


def table() -> str:
    d = load()
    lines = []
    for p, splits in d["periods"].items():
        for s, label in (("test", "Test assets"), ("dev", "Dev assets"), ("control", "Control (Coinbase--Bitstamp)")):
            r = splits[s]
            if r["n_hours"] == 0:
                continue
            lines.append(f"{p.replace('-', '--')} & {label} & {r['n_hours']:,} & {_s(r['b1'])} & {_s(r['b2'])} & {_s(r['est'])} "
                         f"& {_f(r['month_block_ci']['est'])} \\\\")
        lines.append("\\midrule")
    h = d["honest"]
    for s, label in (("test", "Test assets"), ("dev", "Dev assets"), ("control", "Control (Coinbase--Bitstamp)")):
        r = h["score_2020_2023"][s]
        lines.append(f"2020--2023, $c={_num(h['chosen_constant'], 2)}$ re-picked on 2017--2019 & {label} & {r['n_hours']:,} & "
                     f"{_s(r['b1'])} & {_s(r['b2'])} & {_s(r['est'])} & {_f(r['month_block_ci']['est'])} \\\\")
    return (f"{HEADER}\n\\begin{{table*}}[t]\n\\footnotesize\n"
            "\\caption{Assets-by-time holdout: share of the Bitfinex--Coinbase gap removed on withheld assets, by period, with "
            "95\\% bootstrap intervals. Scores are post hoc and descriptive.}\n"
            "\\label{tab:robust-eval}\n\\setlength{\\tabcolsep}{3pt}\n\\begin{tabular}{@{}llrllll@{}}\n\\toprule\n"
            "Period & Set & Hours & $b_1$ & $b_2$ & Estimator & Estimator, 95\\% CI \\\\\n\\midrule\n" + "\n".join(lines)
            + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n")


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())
    print(f"wrote {NUMBERS} and {TABLE}")


if __name__ == "__main__":
    main()
