    ("NumUsdcCoinbaseMedAbsCrisis", ROB, "alternative_dollar_leg/usdc_coinbase_btcusd/crisis/median_abs_bps", _fmt(2)),
    ("NumAnchorExtremeBps", ANCHOR, "r1/extreme_deviation_bps", _fmt(0)),
