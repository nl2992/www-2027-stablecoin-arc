"""Macros and table for the anchored-test robustness grid, from reports/theory/robustness.json.

Writes paper/generated/robust_anchor_numbers.tex (macros ``\\NumRA...``, each with a source comment) and robust_anchor_table.tex.
Source: ``uv run python -m www_theory.robustness``.  Run: ``uv run python -m www_paper.robust_anchor_macros``.
Level tags: windows Stress, Mar, JanMay, Year, Pm; instrument sets Eth, EthLtc, Four, Lags; references Bst, Cb, Mid; X Med, Last;
blocks Day, Week, Month.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "robust_anchor_numbers.tex"
TABLE = GEN / "robust_anchor_table.tex"
REPORT = ROOT / "reports/theory/robustness.json"
SRC = "reports/theory/robustness.json"
HEADER = "% generated by www_paper.robust_anchor_macros; do not edit"
MINUS = "\\ensuremath{-}"
EST = {"ols": "Ols", "iv": "Iv", "gmm": "Gmm"}
LEVELS = {"window": ("Win", {"stress": ("Stress", "Stress window, 2018-11-27 to 2019-05-31"), "stress_to_mar": ("Mar", "2018-11-27 to 2019-03-31"),
                             "jan_to_may_2019": ("JanMay", "2019-01-01 to 2019-05-31"), "year_2019": ("Year", "2019, full year"),
                             "stress_pm30d": ("Pm", "Stress window $\\pm$ 30 days")}),
          "instruments": ("Ins", {"eth": ("Eth", "ETH gap only"), "eth_ltc": ("EthLtc", "ETH, LTC"),
                                  "eth_ltc_bch_etc": ("Four", "ETH, LTC, BCH, ETC (headline)"), "lags12": ("Lags", "Two lags of $L$ only")}),
          "reference": ("Ref", {"bitstamp": ("Bst", "Bitstamp (headline)"), "coinbase": ("Cb", "Coinbase"), "mid": ("Mid", "Median of Bitstamp and Coinbase")}),
          "x": ("X", {"median": ("Med", "Kraken hourly median (headline)"), "last": ("Last", "Kraken hourly last close")}),
          "block": ("Blk", {"day": ("Day", "Block 1 day"), "week": ("Week", "Block 1 week (headline)"), "month": ("Month", "Block 1 month")})}
FACTOR_NAME = {"window": "window", "instruments": "instruments", "reference": "reference for $L$", "x": "external price $X$", "block": "bootstrap block"}


def _load() -> Any:
    return json.loads(REPORT.read_text())


def num(v: float, d: int) -> str:
    s = f"{v:,.{d}f}"
    if s.startswith("-"):
        return s[1:] if not s.strip("-0.,") else MINUS + s[1:]
    return s


def pval(p: float | None) -> str:
    if p is None:
        return "--"
    return "\\ensuremath{<}0.001" if p < 0.001 else num(p, 3 if p < 0.01 else 2)


def pct(v: float) -> str:
    return num(100 * v, 0)


def macros() -> list[tuple[str, str, str]]:
    d = _load()
    out: list[tuple[str, str, str]] = []

    def add(name: str, val: str, src: str) -> None:
        out.append((f"NumRA{name}", val, f"{SRC} {src}"))

    g = d["grid"]
    add("Cells", num(g["cells"], 0), "grid/cells")
    add("Draws", num(g["draws"], 0), "grid/draws")
    add("Seed", str(g["seed"]), "grid/seed")
    add("BlockDayHours", num(g["blocks_hours"]["day"], 0), "grid/blocks_hours/day")
    add("BlockWeekHours", num(g["blocks_hours"]["week"], 0), "grid/blocks_hours/week")
    add("BlockMonthHours", num(g["blocks_hours"]["month"], 0), "grid/blocks_hours/month")
    for e, E in EST.items():
        s = d["summary"]["overall"][e]
        for key, tag, f in (("min", "Min", lambda v: num(v, 3)), ("median", "Med", lambda v: num(v, 3)), ("max", "Max", lambda v: num(v, 3)),
                            ("share_boot_ci_contains_1", "BootOnePct", pct), ("share_boot_ci_excludes_0", "BootZeroPct", pct),
                            ("share_hac_ci_contains_1", "HacOnePct", pct), ("share_hac_ci_excludes_0", "HacZeroPct", pct)):
            add(f"{E}{tag}", f(s[key]), f"summary/overall/{e}/{key}")
    for fac, (pre, lv) in LEVELS.items():
        for k, (tag, _) in lv.items():
            s = d["summary"]["gmm_by_factor"][fac][k]
            for key, t, f in (("min", "Min", lambda v: num(v, 3)), ("median", "Med", lambda v: num(v, 3)), ("max", "Max", lambda v: num(v, 3)),
                              ("share_boot_ci_contains_1", "BootOnePct", pct)):
                add(f"{pre}{tag}{t}", f(s[key]), f"summary/gmm_by_factor/{fac}/{k}/{key}")
    sm = d["summary"]
    add("OutsideCells", num(len(sm["outside_0.9_1.1"]), 0), "summary/outside_0.9_1.1 (cells with any estimator below 0.9 or above 1.1)")
    add("OutsideGmmCells", num(sm["outside_0.9_1.1_gmm_cells"], 0), "summary/outside_0.9_1.1_gmm_cells")
    add("GmmBootExcludesOneCells", num(sm["gmm_boot_ci_excludes_1_count"], 0), "summary/gmm_boot_ci_excludes_1_count")
    h = d["headline"]
    add("HeadN", num(h["n"], 0), "headline/n")
    add("HeadLam", num(h["lam"], 3), "headline/lam")
    add("HeadHacLo", num(h["hac_ci95"][0], 3), "headline/hac_ci95[0]")
    add("HeadHacHi", num(h["hac_ci95"][1], 3), "headline/hac_ci95[1]")
    add("HeadBootLo", num(h["boot_ci95_week"][0], 3), "headline/boot_ci95_week[0] (1-week blocks)")
    add("HeadBootHi", num(h["boot_ci95_week"][1], 3), "headline/boot_ci95_week[1] (1-week blocks)")
    add("HeadJ", num(h["J"], 2), "headline/J")
    add("HeadJDf", num(h["J_df"], 0), "headline/J_df")
    add("HeadJP", pval(h["J_p"]), "headline/J_p")
    add("HeadInstruments", num(len(h["instrument_columns"]), 0), "headline/instrument_columns (count, excluding the constant)")
    add("HeadMoments", num(h["moment_conditions"], 0), "headline/moment_conditions (instruments plus the constant)")
    add("HeadParams", num(h["parameters"], 0), "headline/parameters (lambda and the intercept)")
    add("HeadInstrumentList", "ETH, LTC, BCH and ETC gaps (Bitfinex vs Coinbase)", "headline/instruments")
    a = d["a3_falsification"]
    c, lag = a["contemporaneous"], a["X_on_L_lag1h"]
    add("AThreeN", num(c["n"], 0), "a3_falsification/contemporaneous/n")
    add("AThreeSlope", num(c["slope"], 3), "a3_falsification/contemporaneous/slope")
    add("AThreeHacLo", num(c["hac_ci95"][0], 3), "a3_falsification/contemporaneous/hac_ci95[0]")
    add("AThreeHacHi", num(c["hac_ci95"][1], 3), "a3_falsification/contemporaneous/hac_ci95[1]")
    for bn, B in (("day", "Day"), ("week", "Week"), ("month", "Month")):
        add(f"AThreeBoot{B}Lo", num(c["boot_ci95"][bn][0], 3), f"a3_falsification/contemporaneous/boot_ci95/{bn}[0]")
        add(f"AThreeBoot{B}Hi", num(c["boot_ci95"][bn][1], 3), f"a3_falsification/contemporaneous/boot_ci95/{bn}[1]")
    add("AThreeP", pval(c["p_zero_hac"]), "a3_falsification/contemporaneous/p_zero_hac")
    add("AThreeRTwo", num(c["r2"], 2), "a3_falsification/contemporaneous/r2")
    add("AThreeSdL", num(a["sd_L_bps"], 0), "a3_falsification/sd_L_bps")
    add("AThreeSlopeSd", num(c["slope_x_sd_L_bps"], 0), "a3_falsification/contemporaneous/slope_x_sd_L_bps")
    add("AThreeCorr", num(a["corr_X_L"], 2), "a3_falsification/corr_X_L")
    add("AThreeLagSlope", num(lag["slope"], 3), "a3_falsification/X_on_L_lag1h/slope")
    add("AThreeLagHacLo", num(lag["hac_ci95"][0], 3), "a3_falsification/X_on_L_lag1h/hac_ci95[0]")
    add("AThreeLagHacHi", num(lag["hac_ci95"][1], 3), "a3_falsification/X_on_L_lag1h/hac_ci95[1]")
    return out


def numbers() -> str:
    return "\n".join([HEADER] + [f"\\newcommand{{\\{n}}}{{{v}}} % {s}" for n, v, s in macros()]) + "\n"


def table() -> str:
    d = _load()
    sm, a = d["summary"], d["a3_falsification"]["contemporaneous"]

    def row(label: str, s: dict[str, Any]) -> str:
        return " & ".join([label, num(s["cells"], 0), num(s["min"], 3), num(s["median"], 3), num(s["max"], 3),
                           pct(s["share_boot_ci_contains_1"]) + "\\%", pct(s["share_boot_ci_excludes_0"]) + "\\%"]) + " \\\\"

    rows = [row({"ols": "OLS", "iv": "IV (2SLS)", "gmm": "GMM (all cells)"}[e], sm["overall"][e]) for e in EST]
    for fac, (_, lv) in LEVELS.items():
        rows.append(f"\\midrule\n\\multicolumn{{7}}{{@{{}}l}}{{\\emph{{GMM by {FACTOR_NAME[fac]}}}}} \\\\")
        rows += [row("\\quad " + label, sm["gmm_by_factor"][fac][k]) for k, (_, label) in lv.items()]
    cap = (f"Robustness of the anchored Bitfinex estimate. Each of {num(d['grid']['cells'], 0)} cells crosses five windows, four instrument sets, "
           "three reference venues for $L$, two external USDT prices $X$ and three bootstrap block lengths (fixed before running); "
           "$\\hat\\lambda$ is estimated by OLS, 2SLS and two-step GMM, and the intervals are moving-block-bootstrap "
           f"({num(d['grid']['draws'], 0)} draws). Columns give the number of cells, the minimum, median and maximum of $\\hat\\lambda$, "
           "and the share of cells whose bootstrap 95\\% interval contains 1 or excludes 0. "
           f"Falsification of A3: regressing Kraken's USDT deviation $X$ on $L$ in the stress window gives a slope of {num(a['slope'], 3)} "
           f"(HAC 95\\% CI {num(a['hac_ci95'][0], 3)} to {num(a['hac_ci95'][1], 3)}; one-week block bootstrap "
           f"{num(a['boot_ci95']['week'][0], 3)} to {num(a['boot_ci95']['week'][1], 3)}).")
    return f"""{HEADER}
\\begin{{table}}[t]
\\footnotesize
\\caption{{{cap}}}
\\label{{tab:robust_anchor}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lrrrrrr@{{}}}}
\\toprule
 & Cells & Min $\\hat\\lambda$ & Median & Max & CI $\\ni 1$ & CI $\\not\\ni 0$ \\\\
\\midrule
{chr(10).join(rows)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    for path, text in ((NUMBERS, numbers()), (TABLE, table())):
        path.write_text(text)
        print(f"WROTE {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
