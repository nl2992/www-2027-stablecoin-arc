"""Macros and table for Q1 (frozen fuser on majority-unit events), from reports/q1/gate.json and results.json.

Writes paper/generated/q1_numbers.tex (macros ``\\NumQ...``, each naming its source) and q1_table.tex.
    uv run python -m www_paper.q1_macros
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GATE = ROOT / "reports/q1/gate.json"
RESULTS = ROOT / "reports/q1/results.json"
NUMBERS = ROOT / "paper/generated/q1_numbers.tex"
TABLE = ROOT / "paper/generated/q1_table.tex"
HEADER = "% generated by www_paper.q1_macros; do not edit"
MINUS = "\\ensuremath{-}"
EV = {"Q-E1": "EOne", "Q-E2": "ETwo", "Q-E3": "EThree", "Q-E4": "EFour", "Q-E5": "EFive"}
MT = {"fuser": "Fuser", "B0": "BZero", "B1": "BOne", "B2": "BTwo", "B3": "BThree", "B4": "BFour", "oracle": "Oracle"}


def f(x: float, nd: int = 2) -> str:
    s = f"{x:.{nd}f}"
    return MINUS + s[1:] if s.startswith("-") else s


def numbers() -> str:
    g, r = json.loads(GATE.read_text()), json.loads(RESULTS.read_text())
    out = [HEADER]

    def add(name: str, val: str, src: str, file: str = "results") -> None:
        out.append(f"\\newcommand{{\\NumQ{name}}}{{{val}}} % reports/q1/{file}.json {src}")

    for e, v in g["events"].items():
        add(f"SHi{EV[e]}", str(v["s_hi_hours"]), f"events/{e}/s_hi_hours", "gate")
    add("SHiPooled", str(g["pooled_s_hi_hours"]), "pooled_s_hi_hours", "gate")
    add("NKept", str(g["n_kept"]), "n_kept", "gate")
    for tag, k in (("B", "fuser_vs_B0"), ("Bc", "fuser_vs_B2"), ("Bd", "fuser_vs_B3")):
        p = r["primary"][k]
        name = {"B": "VsBZero", "Bc": "VsBTwo", "Bd": "VsBThree"}[tag]
        add(f"{name}Mean", f(p["mean"]), f"primary/{k}/mean")
        add(f"{name}Lo", f(p["ci95"][0]), f"primary/{k}/ci95[0]")
        add(f"{name}Hi", f(p["ci95"][1]), f"primary/{k}/ci95[1]")
    add("NHours", str(r["primary"]["fuser_vs_B0"]["n_hours"]), "primary/fuser_vs_B0/n_hours")
    add("NBlocks", str(r["primary"]["fuser_vs_B0"]["n_blocks"]), "primary/fuser_vs_B0/n_blocks")
    for m, t in MT.items():
        s = r["pooled_s_hi"][m]
        add(f"Mae{t}", f(s["mae"], 1), f"pooled_s_hi/{m}/mae")
        add(f"PNinetyFive{t}", f(s["p95"], 1), f"pooled_s_hi/{m}/p95")
        add(f"NTwentyFive{t}", str(s["n25"]), f"pooled_s_hi/{m}/n25")
        add(f"NFifty{t}", str(s["n50"]), f"pooled_s_hi/{m}/n50")
    add("GapOracle", f(r["gap_to_oracle_s_hi"]), "gap_to_oracle_s_hi")
    for e in r["kept_events"]:
        add(f"Ratio{EV[e]}", f(r["per_event"][e]["mae_ratio_s_hi"]["fuser"]), f"per_event/{e}/mae_ratio_s_hi/fuser")
        add(f"Placebo{EV[e]}", f(r["placebo"]["per_event"][e]["ratio"]), f"placebo/per_event/{e}/ratio")
    add("PlaceboPooled", f(r["placebo"]["pooled_ratio"]), "placebo/pooled_ratio")
    return "\n".join(out) + "\n"


def table() -> str:
    g, r = json.loads(GATE.read_text()), json.loads(RESULTS.read_text())
    rows = [HEADER, "\\begin{tabular}{lrrrrr}", "\\toprule",
            "Event & $S_{hi}$ h & Fuser/B0 & B2/B0 & B3/B0 & Oracle/B0 \\\\", "\\midrule"]
    for e in r["kept_events"]:
        q = r["per_event"][e]["mae_ratio_s_hi"]
        rows.append(f"{e} & {g['events'][e]['s_hi_hours']} & {f(q['fuser'])} & {f(q['B2'])} & {f(q['B3'])} & {f(q['oracle'])} \\\\")
    pm = r["pooled_s_hi"]
    rows += ["\\midrule", f"Pooled & {g['pooled_s_hi_hours']} & {f(pm['fuser']['mae'] / pm['B0']['mae'])} & "
             f"{f(pm['B2']['mae'] / pm['B0']['mae'])} & {f(pm['B3']['mae'] / pm['B0']['mae'])} & "
             f"{f(pm['oracle']['mae'] / pm['B0']['mae'])} \\\\", "\\bottomrule", "\\end{tabular}"]
    return "\n".join(rows) + "\n"


def main() -> None:
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())


if __name__ == "__main__":
    main()
