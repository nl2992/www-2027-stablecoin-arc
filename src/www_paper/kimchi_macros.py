"""Macros and table for the Kimchi application, from reports/kimchi/results.json.

Writes paper/generated/kimchi_numbers.tex (macros ``\\NumKR...``, each naming its source) and kimchi_table.tex.
    uv run python -m www_paper.kimchi_macros
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / "reports/kimchi/results.json"
NUMBERS = ROOT / "paper/generated/kimchi_numbers.tex"
TABLE = ROOT / "paper/generated/kimchi_table.tex"
HEADER = "% generated by www_paper.kimchi_macros; do not edit"
MINUS = "\\ensuremath{-}"
ROWS = [("E1_2017-12_2018-01", "Dec 2017--Jan 2018 (high)"), ("E2_2021-03_2021-05", "Mar--May 2021 (high)"),
        ("E3_2022-05_2022-06", "May--Jun 2022 (Luna)"), ("C1_2019", "2019 (control)"), ("C2_2020", "2020 (control)"),
        ("C3_2023-01_2023-11", "Jan--Nov 2023 (control)")]
TAG = {"E1_2017-12_2018-01": "EOne", "E2_2021-03_2021-05": "ETwo", "E3_2022-05_2022-06": "EThree", "C1_2019": "COne",
       "C2_2020": "CTwo", "C3_2023-01_2023-11": "CThree"}
YEAR = {2017: "Y2017", 2018: "Y2018", 2019: "Y2019", 2020: "Y2020", 2021: "Y2021", 2022: "Y2022", 2023: "Y2023"}
YW = {"2017": "YSeventeen", "2018": "YEighteen", "2019": "YNineteen", "2020": "YTwenty", "2021": "YTwentyOne", "2022": "YTwentyTwo",
      "2023": "YTwentyThree"}


def _load() -> dict:
    return json.loads(REPORT.read_text())


def f(x: float, nd: int = 3) -> str:
    s = f"{x:.{nd}f}"
    return MINUS + s[1:] if s.startswith("-") else s


def pct(bps: float) -> str:
    return f(bps / 100, 1)


def numbers() -> str:
    r = _load()
    out = [HEADER]

    def add(name: str, val: str, src: str) -> None:
        out.append(f"\\newcommand{{\\NumKR{name}}}{{{val}}} % reports/kimchi/results.json {src}")

    for k, tag in TAG.items():
        w = r["windows"][k]
        c = w["common"]
        add(f"{tag}BtcPremPct", pct(w["premium"]["BTC"]["median_bps"]), f"windows/{k}/premium/BTC/median_bps (bps/100)")
        add(f"{tag}MinCorr", f(c["min_corr_levels"]), f"windows/{k}/common/min_corr_levels")
        add(f"{tag}CorrLo", f(c["median_corr_levels_ci95_week"][0]), f"windows/{k}/common/median_corr_levels_ci95_week/0")
        add(f"{tag}MinLooR", f(c["min_loo_r2"], 2), f"windows/{k}/common/min_loo_r2")
        add(f"{tag}PcShare", f(c["pc1_share"]), f"windows/{k}/common/pc1_share")
        add(f"{tag}MinCorrChg", f(min(c["corr_changes"].values()), 2), f"windows/{k}/common/corr_changes (min)")
        add(f"{tag}Days", str(c["days"]), f"windows/{k}/common/days")
    for y, tag in YW.items():
        c = r["by_year"][y]["common"]
        add(f"{tag}MinCorr", f(c["min_corr_levels"]), f"by_year/{y}/common/min_corr_levels")
    yc = [r["by_year"][y]["common"]["min_corr_levels"] for y in r["by_year"]]
    add("YearsMinCorr", f(min(yc)), "by_year/*/common/min_corr_levels (min over 2017-2023)")
    add("HOneSupported", "yes" if r["H1"]["supported"] else "no", "H1/supported")
    a = r["anchor"]
    for key, tag in (("mean3_vs_bch_iv", "Mean"), ("btc_only_vs_eth_iv", "Btc"), ("fx_lag1_mean3", "Lag")):
        b = a[key]
        add(f"Anch{tag}N", str(b["n"]), f"anchor/{key}/n")
        for est, t2 in (("slope_D_minus_X_on_L_ols", "Ols"), ("slope_D_minus_X_on_L_iv", "Iv")):
            add(f"Anch{tag}{t2}", f(b[est]["est"], 2), f"anchor/{key}/{est}/est")
            add(f"Anch{tag}{t2}Lo", f(b[est]["ci95"][0], 2), f"anchor/{key}/{est}/ci95/0")
            add(f"Anch{tag}{t2}Hi", f(b[est]["ci95"][1], 2), f"anchor/{key}/{est}/ci95/1")
        add(f"Anch{tag}PlainOls", f(b["slope_D_on_L_ols"]["est"], 2), f"anchor/{key}/slope_D_on_L_ols/est")
    b = a["mean3_vs_bch_iv"]
    add("AnchMedianLPct", pct(b["median_L"]), "anchor/mean3_vs_bch_iv/median_L (bps/100)")
    add("AnchMedianDPct", pct(b["median_D"]), "anchor/mean3_vs_bch_iv/median_D (bps/100)")
    add("AnchMedianXBps", f(b["median_X"], 1), "anchor/mean3_vs_bch_iv/median_X")
    add("AnchSdXBps", f(b["sd_X"], 1), "anchor/mean3_vs_bch_iv/sd_X")
    add("AnchStart", a["window"][0], "anchor/window/0")
    add("AnchFirstUsdt", a["usdt_krw_first_candle"][:10], "anchor/usdt_krw_first_candle")
    return "\n".join(out) + "\n"


def table() -> str:
    r = _load()
    a = r["anchor"]["mean3_vs_bch_iv"]
    o = [HEADER, "\\begin{table}[t]", "\\footnotesize",
         "\\caption{Kimchi premium on Upbit against Coinbase/Bitstamp dollar prices converted at FRED DEXKOUS. "
         "Gaps are medians of UTC days (at least 12 hours). The pre-registered high-premium windows are the first two rows. "
         "Min corr is the smallest pairwise correlation of daily gaps among BTC, ETH and XRP (levels); the interval is a weekly "
         "block bootstrap of the median pair correlation; Min LOO $R^2$ is the weakest leave-one-out share. The Bithumb "
         "USDT/KRW anchor exists only from 2023-12-07; the anchored slope of $(D-X)$ on the common gap, 2023-12-08 to 2023-12-31 "
         "(hourly, day-block bootstrap), is "
         f"{f(a['slope_D_minus_X_on_L_ols']['est'], 2)} OLS (95\\% interval {f(a['slope_D_minus_X_on_L_ols']['ci95'][0], 2)}--"
         f"{f(a['slope_D_minus_X_on_L_ols']['ci95'][1], 2)}) and {f(a['slope_D_minus_X_on_L_iv']['est'], 2)} IV. "
         "The anchor cannot be run in any high-premium window.}", "\\label{tab:kimchi}",
         "\\begin{tabular}{@{}lrrcrr@{}}", "\\toprule",
         "Window & BTC gap (\\%) & Min corr & Corr interval & Min LOO $R^2$ & PC1 share \\\\", "\\midrule"]
    for k, lab in ROWS:
        w = r["windows"][k]
        c = w["common"]
        ci = c["median_corr_levels_ci95_week"]
        o.append(f"{lab} & {pct(w['premium']['BTC']['median_bps'])} & {f(c['min_corr_levels'])} & "
                 f"[{f(ci[0])}, {f(ci[1])}] & {f(c['min_loo_r2'], 2)} & {f(c['pc1_share'])} \\\\")
    o += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(o) + "\n"


def main() -> int:
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())
    print(f"wrote {NUMBERS} and {TABLE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
