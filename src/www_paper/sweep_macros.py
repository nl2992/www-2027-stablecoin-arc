"""Macros and a compact table for the monitor operating-curve sweep (reports/rescue/monitor_sweep.json).

Writes paper/generated/sweep_numbers.tex (prefix NumS...) and paper/generated/monitor_sweep_table.tex.
Source: ``uv run python -m www_rescue.monitor_sweep``. Run: ``uv run python -m www_paper.sweep_macros``.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "sweep_numbers.tex"
TABLE = GEN / "monitor_sweep_table.tex"
SWEEP = ROOT / "reports/rescue/monitor_sweep.json"
SJ = "reports/rescue/monitor_sweep.json"
HEADER = "% generated by www_paper.sweep_macros; do not edit"
TABLE_LEVELS = ("0.6", "0.85", "1")
ROW_LABEL = (("detector_a0.25", "Monitor"), ("b1", "Gap only"), ("two_asset", "Two-asset gap"),
             ("b2", "Robust $z$"), ("b3", "USDT premium"))
SHORT = {"detector_a0.25": "Det", "detector_a0.1": "DetLoose", "detector_a0.5": "DetStrict", "b1": "BOne",
         "two_asset": "Two", "b2": "BTwo", "b3": "BThree"}
VSHORT = {"bitfinex": "Bfx", "binance_us": "Bus", "coinbase": "Cb", "pooled": "Pool"}
LEVEL_WORD = {"0.6": "Sixty", "0.7": "Seventy", "0.85": "EightyFive", "1": "Full"}
RELATION_OK = ("dominates", "identical")


def _load() -> Any:
    return json.loads(SWEEP.read_text())


def _long(d: str) -> str:
    return date.fromisoformat(d).strftime("%-d %B %Y")


def macros() -> list[tuple[str, str, str]]:
    s = _load()
    sw, cv, ex, tl, dom = s["sweep"], s["curves"], s["exposure"], s["timeline"], s["dominance"]
    m: list[tuple[str, str, str]] = []
    for meth, key in (("detector_a0.25", "100"), ("b1", "100"), ("two_asset", "100"), ("b2", "4")):
        for v in ("bitfinex", "binance_us", "coinbase", "pooled"):
            d = sw[meth][key][v]
            src = f"{SJ} sweep/{meth}/{key}/{v}"
            m += [(f"NumS{SHORT[meth]}Fa{VSHORT[v]}", str(d["false_alarm_episodes"]), f"{src}/false_alarm_episodes"),
                  (f"NumS{SHORT[meth]}Rate{VSHORT[v]}", f"{d['fa_per_venue_year']:.2f}", f"{src}/fa_per_venue_year"),
                  (f"NumS{SHORT[meth]}Caught{VSHORT[v]}", str(d["caught"]), f"{src}/caught"),
                  (f"NumS{SHORT[meth]}Covered{VSHORT[v]}", str(d["covered_positives"]), f"{src}/covered_positives")]
    for meth in ("detector_a0.25", "b1", "two_asset", "b2"):
        for scope in ("bitfinex", "pooled"):
            for lv, word in LEVEL_WORD.items():
                val = cv[meth][scope]["at_recall"][lv]
                m.append((f"NumS{SHORT[meth]}At{word}{VSHORT[scope]}", "--" if val is None else f"{val:.2f}",
                          f"{SJ} curves/{meth}/{scope}/at_recall/{lv} (minimum false alarms per venue-year at recall >= {lv})"))
    for scope in ("bitfinex", "binance_us", "coinbase", "pooled"):
        for other, w in (("b1", "BOne"), ("two_asset", "Two")):
            rows = dom[scope][other]
            m.append((f"NumSDomOk{w}{VSHORT[scope]}", str(sum(r["relation"] in RELATION_OK for r in rows)),
                      f"{SJ} dominance/{scope}/{other}: thresholds at which the monitor dominates or equals (of {len(rows)})"))
            m.append((f"NumSDomWorse{w}{VSHORT[scope]}", str(sum(r["relation"] in ("dominated", "incomparable") for r in rows)),
                      f"{SJ} dominance/{scope}/{other}: thresholds at which the monitor is dominated or incomparable"))
    pv = ex["per_venue_method"]
    for meth, w in (("detector", "Det"), ("b1", "BOne"), ("two_asset", "Two")):
        for v in ("bitfinex", "binance_us", "coinbase"):
            r = pv[v][meth]
            m += [(f"NumSHours{w}{VSHORT[v]}", f"{r['evaluated_hours']:,}".replace(",", "{,}"),
                   f"{SJ} exposure/per_venue_method/{v}/{meth}/evaluated_hours"),
                  (f"NumSYears{w}{VSHORT[v]}", f"{r['venue_years']:.2f}", f"{SJ} exposure/per_venue_method/{v}/{meth}/venue_years")]
    pd_ = ex["pooled_detector_denominator"]
    m += [("NumSPooledEntries", str(pd_["covered_entries"]), f"{SJ} exposure/pooled_detector_denominator/covered_entries"),
          ("NumSPooledUnique", str(pd_["unique_covered_labels"]), f"{SJ} exposure/pooled_detector_denominator/unique_covered_labels"),
          ("NumSPooledUniqueCaught", str(pd_["unique_caught_at_any_venue"]),
           f"{SJ} exposure/pooled_detector_denominator/unique_caught_at_any_venue")]
    nyag = tl["label_dates"]["nyag_disclosure"]["first_public_report_date"]
    m += [("NumSFirstDayAbove", _long(tl["first_day_above_100bps_2018H2"]), f"{SJ} timeline/first_day_above_100bps_2018H2"),
          ("NumSFirstDayAboveIso", tl["first_day_above_100bps_2018H2"], f"{SJ} timeline/first_day_above_100bps_2018H2"),
          ("NumSFirstRunDays", str(tl["first_run_days"]), f"{SJ} timeline/first_run_days (consecutive days above 100 bps)"),
          ("NumSDaysAboveToNyag", str(tl["days_above_100bps_first_day_to_day_before_nyag"]),
           f"{SJ} timeline/days_above_100bps_first_day_to_day_before_nyag"),
          ("NumSCalendarDaysToNyag", str(tl["calendar_days_first_day_to_nyag"]), f"{SJ} timeline/calendar_days_first_day_to_nyag"),
          ("NumSMonthsToNyag", f"{tl['months_first_day_to_nyag']:.1f}", f"{SJ} timeline/months_first_day_to_nyag"),
          ("NumSNyagDate", _long(nyag), f"{SJ} timeline/label_dates/nyag_disclosure"),
          ("NumSDepositPauseDate", _long(tl["label_dates"]["first_public_deposit_pause_report"]["first_public_report_date"]),
           f"{SJ} timeline/label_dates/first_public_deposit_pause_report"),
          ("NumSNobleDate", _long(tl["label_dates"]["first_public_banking_partner_report_2018"]["first_public_report_date"]),
           f"{SJ} timeline/label_dates/first_public_banking_partner_report_2018"),
          ("NumSFirstAlarmDay", _long(tl["first_alarm_day_2018H2_by_method_at_100bps"]["detector"]),
           f"{SJ} timeline/first_alarm_day_2018H2_by_method_at_100bps/detector")]
    return m


def numbers() -> str:
    return "\n".join([HEADER, *(f"\\newcommand{{\\{n}}}{{{v}}} % {src}" for n, v, src in macros())]) + "\n"


def _cell(v: float | None) -> str:
    return "--" if v is None else f"{v:.2f}"


def table() -> str:
    cv = _load()["curves"]
    rows = []
    for key, label in ROW_LABEL:
        cells = []
        for lv in TABLE_LEVELS:
            for scope in ("bitfinex", "pooled"):
                c = cv[key][scope]
                cells.append("--" if c is None or (key == "b3" and scope == "pooled") else _cell(c["at_recall"][lv]))
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    head = " & ".join(f"\\multicolumn{{2}}{{c}}{{$\\geq${float(lv):.0%}}}".replace("%", "\\%") for lv in TABLE_LEVELS)
    rules = "".join(f"\\cmidrule(lr){{{2 + 2 * i}-{3 + 2 * i}}}" for i in range(len(TABLE_LEVELS)))
    return (f"{HEADER}\n\\begin{{table}}[t]\n\\small\n"
            "\\caption{Monitor operating curves: the fewest false-alarm episodes per exchange-year over each method's sweep "
            "(gap thresholds 25--300 bps; $k=3$--6 for the robust $z$) that still reach the stated episode recall, on "
            "Bitfinex and pooled over exchanges. The monitor uses second-asset agreement 0.25. -- means the recall is "
            "never reached (or, for the USDT premium, no pooled version).}\n"
            "\\label{tab:sweep}\n\\setlength{\\tabcolsep}{3pt}\n\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n"
            f"Method & {head} \\\\\n{rules}\n"
            " & Bfx & Pooled & Bfx & Pooled & Bfx & Pooled \\\\\n\\midrule\n" + "\n".join(rows)
            + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    for path, text in ((NUMBERS, numbers()), (TABLE, table())):
        path.write_text(text)
        print(f"WROTE {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
