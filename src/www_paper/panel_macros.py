"""Macros and table for the pre-registered currency-wedge panel, from reports/panel/results.json.

Writes paper/generated/panel_numbers.tex (macros ``\\NumPN...``, letters only, each with a source comment) and panel_table.tex.
Source: ``uv run python -m www_panel.run``. Run: ``uv run python -m www_paper.panel_macros``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "paper/generated"
NUMBERS = GEN / "panel_numbers.tex"
TABLE = GEN / "panel_table.tex"
REPORT = ROOT / "reports/panel/results.json"
HEADER = "% generated by www_paper.panel_macros; do not edit"
SRC = "reports/panel/results.json"
MINUS = "\\ensuremath{-}"
ORDER = ("ARS", "BRL", "KRW", "NGN", "RUB", "TRY", "UAH", "ZAR")


def _load() -> Any:
    return json.loads(REPORT.read_text())


def f(v: float, d: int = 3) -> str:
    s = f"{v:.{d}f}"
    return s.replace("-", MINUS) if s.startswith("-") else s


def _tag(cur: str) -> str:
    return cur[0] + cur[1:].lower()


def yn(b: bool) -> str:
    return "yes" if b else "no"


def numbers() -> str:
    r = _load()
    out = [HEADER]

    def add(name: str, val: str, src: str) -> None:
        out.append(f"\\newcommand{{\\NumPN{name}}}{{{val}}} % {SRC} {src}")

    for key, tag in (("pooled_stress", "Stress"), ("pooled_calm", "Calm")):
        e = r[key]
        add(f"Pooled{tag}Lam", f(e["iv"]["lam"]), f"{key}/iv/lam")
        add(f"Pooled{tag}Lo", f(e["iv"]["lo"]), f"{key}/iv/lo")
        add(f"Pooled{tag}Hi", f(e["iv"]["hi"]), f"{key}/iv/hi")
        add(f"Pooled{tag}Ols", f(e["ols"]["lam"]), f"{key}/ols/lam")
        add(f"Pooled{tag}Days", f"{e['n_days']:,}", f"{key}/n_days")
        add(f"Pooled{tag}Hours", f"{e['n_hours']:,}", f"{key}/n_hours")
    for cur in ORDER:
        c, t = r["by_currency"][cur], _tag(cur)
        add(f"{t}Lam", f(c["stress"]["iv"]["lam"]), f"by_currency/{cur}/stress/iv/lam")
        add(f"{t}Lo", f(c["stress"]["iv"]["lo"]), f"by_currency/{cur}/stress/iv/lo")
        add(f"{t}Hi", f(c["stress"]["iv"]["hi"]), f"by_currency/{cur}/stress/iv/hi")
        add(f"{t}StressMonths", str(c["stress_months"]), f"by_currency/{cur}/stress_months")
    for v in ("binance", "upbit", "bithumb"):
        e = r["by_venue"][v]["stress"]
        add(f"{v.capitalize()}Lam", f(e["iv"]["lam"]), f"by_venue/{v}/stress/iv/lam")
        add(f"{v.capitalize()}Lo", f(e["iv"]["lo"]), f"by_venue/{v}/stress/iv/lo")
        add(f"{v.capitalize()}Hi", f(e["iv"]["hi"]), f"by_venue/{v}/stress/iv/hi")
    p1, p2, fa = r["P1"], r["P2"], r["falsification"]
    add("POnePass", yn(p1["pass"]), "P1/pass")
    add("POneExcludesZero", yn(p1["excludes_0"]), "P1/excludes_0")
    add("POneIncludesOne", yn(p1["includes_1"]), "P1/includes_1")
    add("PTwoPass", yn(p2["pass"]), "P2/pass")
    add("PTwoInside", str(p2["n_inside"]), "P2/n_inside")
    add("PTwoEligible", str(p2["n_eligible"]), "P2/n_eligible")
    add("FalsTriggered", yn(fa["triggered"]), "falsification/triggered")
    add("FalsUpper", f(fa["pooled_upper"]), "falsification/pooled_upper")
    months = r["by_month"]
    lams = sorted(m["iv"]["lam"] for m in months)
    add("MonthCount", str(len(months)), "by_month (count)")
    add("MonthMin", f(lams[0], 2), "by_month/*/iv/lam (min)")
    add("MonthBelowHalf", str(sum(x < 0.5 for x in lams)), "by_month/*/iv/lam < 0.5 (count)")
    rb = r["robustness"]
    add("RobOlsPooled", f(rb["ols_pooled_stress"]["lam"]), "robustness/ols_pooled_stress/lam")
    add("RobDailyLam", f(rb["daily_week_fe"]["pooled_stress"]["iv"]["lam"]), "robustness/daily_week_fe/pooled_stress/iv/lam")
    add("RobDailyLo", f(rb["daily_week_fe"]["pooled_stress"]["iv"]["lo"]), "robustness/daily_week_fe/pooled_stress/iv/lo")
    add("RobDailyHi", f(rb["daily_week_fe"]["pooled_stress"]["iv"]["hi"]), "robustness/daily_week_fe/pooled_stress/iv/hi")
    for key, tag in (("alt_x_binance_us", "AltBus"), ("alt_x_bitstamp", "AltBst")):
        e = rb[key]["pooled_stress"]["iv"]
        add(f"{tag}Lam", f(e["lam"]), f"robustness/{key}/pooled_stress/iv/lam")
        add(f"{tag}Lo", f(e["lo"]), f"robustness/{key}/pooled_stress/iv/lo")
        add(f"{tag}Hi", f(e["hi"]), f"robustness/{key}/pooled_stress/iv/hi")
    return "\n".join(out) + "\n"


def table() -> str:
    r = _load()
    rows = []
    for cur in ORDER:
        c = r["by_currency"][cur]
        e = c["stress"]["iv"]
        if cur in r["P2"]["in_0.8_1.2"]:
            p2 = "in" if r["P2"]["in_0.8_1.2"][cur] else "out"
        else:
            p2 = "--"
        rows.append(f"{cur} & {c['stress_months']} & {c['calm_months']} & {f(e['lam'])} & [{f(e['lo'])}, {f(e['hi'])}] & {p2} \\\\")
    pe = r["pooled_stress"]["iv"]
    p1 = "pass" if r["P1"]["pass"] else "fail"
    pooled = (f"Pooled stress & {sum(c['stress_months'] for c in r['by_currency'].values())} & -- & {f(pe['lam'])} & "
              f"[{f(pe['lo'])}, {f(pe['hi'])}] & P1 {p1} \\\\")
    body = "\n".join(rows)
    return f"""{HEADER}
\\begin{{table}}[t]
\\footnotesize
\\caption{{Currency-wedge panel (pre-registered). Hourly Binance markets in seven local currencies and Upbit and Bithumb in KRW; $(D-X)$ on $L$ with day fixed effects, IV with the ETH gap $L_2$ as instrument. Months are venue-months classified as stress (median $|L-\\mathrm{{med}}(L)|\\ge 25$ bps) or calm from $L$ alone; the 95\\% interval is a 7-day moving-block bootstrap (1,000 draws). P2 marks whether $\\hat\\lambda$ lies in $[0.8,1.2]$ for currencies with at least three stress months.}}
\\label{{tab:panel}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lrrrlr@{{}}}}
\\toprule
Currency & Stress & Calm & $\\hat\\lambda$ (IV) & 95\\% CI & P2 \\\\
\\midrule
{body}
\\midrule
{pooled}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def main() -> int:
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())
    print(f"wrote {NUMBERS} and {TABLE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
