def _load(path: Path) -> Any:
    return json.loads(path.read_text())


def _num(v: float, d: int) -> str:
    s = f"{v:,.{d}f}"
    if s.startswith("-"):
        return s[1:] if not s.strip("-0.,") else MINUS + s[1:]  # no negative zero
    return s


def _cell(v: float | None, d: int = 2) -> str:
    return "--" if v is None else _num(v, d)


def _pct(v: float) -> str:
    return f"{100 * v:.0f}"


def parse_log(path: Path) -> dict[str, str]:
    """``key: value`` lines of a harness log or the recorded dev output."""
    out = {}
    for line in path.read_text().splitlines():
        if ": " in line:
            k, v = line.split(": ", 1)
            out[k.strip()] = v.strip()
    return out


def _floats(log: dict[str, str], prefix: str) -> dict[str, float]:
    return {k[len(prefix):]: float(v) for k, v in log.items() if k.startswith(prefix)}


def loop_counts() -> tuple[int, int]:
    with LOOP_TSV.open() as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    return len(rows), sum(r["status"] == "keep" for r in rows)


def _days(start: str, end: str) -> set[date]:
    a, b = date.fromisoformat(start), date.fromisoformat(end)
    return {date.fromordinal(o) for o in range(a.toordinal(), b.toordinal() + 1)}


def detector_days_in(window: tuple[date, date]) -> int:
    """Days of detector alarm episodes (all monitored venues) that fall inside ``window``.

    Alarm episodes are the stored unit; a day count from episodes is an upper bound on alarm days, and exactly zero
    when no episode overlaps the window."""
    lo, hi = window
    total = 0
    for v in _load(DETECTOR)["metrics"]["all"].values():
        for start, end in v["detector"]["episodes"]:
            total += len({d for d in _days(start, end) if lo <= d <= hi})
    return total


