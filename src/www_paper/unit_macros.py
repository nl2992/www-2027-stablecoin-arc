def t2_table() -> str:
    t2 = _load(T2)
    realistic = {(r["k"], r["fuser"]): r for r in t2["records"] if r["shape"] == "realistic"}
    rows = []
    for fuser, label in T2_FUSER.items():
        cells = []
        for k in (1, 2):
            b = t2["breakdown"][f"k={k}"][fuser]
            cells += [("none" if b["pooled"] is None else str(b["pooled"])),
                      ("none" if b["worst_combo"] is None else str(b["worst_combo"])),
                      f"{realistic[(k, fuser)]['p95_abs_err_bps']:.1f}"]
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    deltas = ", ".join(str(r["delta_bps"]) for r in t2["records"]
                       if r["k"] == 1 and r["fuser"] == "median" and r["shape"] == "constant")
    return (f"{HEADER}\n\\begin{{table}}[t]\n\\footnotesize\n"
            "\\caption{Fusion under an injected unit bias on $k$ of three exchanges (development assets, 2021--2023). "
            "Breakdown: the smallest constant bias in bps (grid: " + deltas + ") at which the 95th percentile of the "
            "absolute fused-price error exceeds 50 bps, pooled over which exchanges are hit and for the worst choice; "
            "none: not reached on the grid. Replay: 95th percentile error in bps when the bias follows the Bitfinex "
            "2018--19 gap.}\n"
            "\\label{tab:t2}\n\\setlength{\\tabcolsep}{3pt}\n\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n"
            " & \\multicolumn{3}{c}{$k=1$} & \\multicolumn{3}{c}{$k=2$} \\\\\n\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n"
            "Fuser & Pooled & Worst & Replay & Pooled & Worst & Replay \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")


