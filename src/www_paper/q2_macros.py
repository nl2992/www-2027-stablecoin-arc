"""Macros and table for Q2 (early detection of unit shifts), from reports/q2/{labels,calibration,results}.json.

Writes paper/generated/q2_numbers.tex (macros ``\\NumQT...``, each naming its source) and q2_table.tex.
    uv run python -m www_paper.q2_macros
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "reports/q2"
NUMBERS = ROOT / "paper/generated/q2_numbers.tex"
TABLE = ROOT / "paper/generated/q2_table.tex"
HEADER = "% generated by www_paper.q2_macros; do not edit"
MINUS = "\\ensuremath{-}"
EV = {"E1": "EOne", "E2": "ETwo", "E3": "EThree", "E4": "EFour", "E5": "EFive", "E6": "ESix"}
DT = {"P": "P", "S1": "SOne", "S2": "STwo"}
CT = {"S1": "SOne", "S2": "STwo"}


def f(x: float, nd: int = 1) -> str:
    s = f"{x:.{nd}f}"
    return MINUS + s[1:] if s.startswith("-") else s


def lead(x) -> str:
    return "miss" if x is None else f(x, 0)


def load():
    return (json.loads((D / n).read_text()) for n in ("labels.json", "calibration.json", "results.json"))


def numbers() -> str:
    lab, cal, res = load()
    out = [HEADER]

    def add(name: str, val: str, src: str, file: str) -> None:
        out.append(f"\\newcommand{{\\NumQT{name}}}{{{val}}} % reports/q2/{file}.json {src}")

    add("NScored", str(len(res["scored_events"])), "scored_events", "results")
    add("NCalmHours", str(cal["n_calm_hours"]), "n_calm_hours", "calibration")
    add("TauP", f(cal["thresholds_bps"]["tau_P"]), "thresholds_bps/tau_P", "calibration")
    add("TauSOne", f(cal["thresholds_bps"]["tau_S1"]), "thresholds_bps/tau_S1", "calibration")
    add("HSTwo", f(cal["thresholds_bps"]["h_S2"], 0), "thresholds_bps/h_S2", "calibration")
    for d, t in DT.items():
        add(f"FalseAlarmRate{t}", f(cal["realised_per_1000_calm_hours"][d], 2), f"realised_per_1000_calm_hours/{d}", "calibration")
        add(f"Misses{t}", str(res["misses"][d]), f"misses/{d}", "results")
        add(f"Median{t}", f(res["median_lead_hours"][d]), f"median_lead_hours/{d}", "results")
    for e, v in lab["events"].items():
        add(f"Max{EV[e]}", f(v["max_abs_dev_bps"], 0), f"events/{e}/max_abs_dev_bps", "labels")
    for e in res["scored_events"]:
        for d, t in DT.items():
            x = res["per_event"][e]["lead_hours"][d]
            if x is not None:
                add(f"Lead{t}{EV[e]}", f(x, 0), f"per_event/{e}/lead_hours/{d}", "results")
    for c, t in CT.items():
        b = res["bootstrap"]["differences_hours"][f"P_minus_{c}"]
        add(f"DiffSub{t}", f(b["point"]), f"bootstrap/differences_hours/P_minus_{c}/point", "results")
        add(f"DiffSub{t}Lo", f(b["ci95"][0]), f"bootstrap/differences_hours/P_minus_{c}/ci95[0]", "results")
        add(f"DiffSub{t}Hi", f(b["ci95"][1]), f"bootstrap/differences_hours/P_minus_{c}/ci95[1]", "results")
    return "\n".join(out) + "\n"


def table() -> str:
    lab, cal, res = load()
    rows = [HEADER, "\\begin{tabular}{llrrrr}", "\\toprule", "Event & Unit & Onset (UTC) & P & S1 & S2 \\\\", "\\midrule"]
    for e, v in res["per_event"].items():
        if not v["scored"]:
            rows.append(f"{e} & {lab['events'][e]['unit']} & unscorable & & & \\\\")
            continue
        l = v["lead_hours"]
        rows.append(f"{e} & {lab['events'][e]['unit']} & {v['onset_utc'][:16]} & {lead(l['P'])} & {lead(l['S1'])} & {lead(l['S2'])} \\\\")
    m = res["median_lead_hours"]
    rows += ["\\midrule", f"Median lead (h) & & & {f(m['P'])} & {f(m['S1'])} & {f(m['S2'])} \\\\",
             f"Misses & & & {res['misses']['P']} & {res['misses']['S1']} & {res['misses']['S2']} \\\\",
             "\\bottomrule", "\\end{tabular}"]
    return "\n".join(rows) + "\n"


def main() -> None:
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())


if __name__ == "__main__":
    main()
