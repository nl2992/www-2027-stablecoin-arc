"""Macros and tables from reports/unit_td/td_realdata.json (``uv run python -m www_auto.td_realdata``).

Writes paper/generated/td_numbers.tex (macro prefix NumT) and paper/generated/td_realdata_table.tex.
Run: ``uv run python -m www_paper.td_macros``.
"""

from __future__ import annotations

import json
from typing import Any

from .unit_macros import GEN, ROOT, _num

HEADER = "% generated by www_paper.td_macros; do not edit"
SRC_FILE = ROOT / "reports/unit_td/td_realdata.json"
NUMBERS = GEN / "td_numbers.tex"
TABLE = GEN / "td_realdata_table.tex"
SRC = "reports/unit_td/td_realdata.json"

M_WORD = {"median": "Median", "vwap": "Vwap", "crh": "Crh", "gtm": "Gtm", "unit_aware": "UnitAware",
          "unit_aware_dep": "UnitAwareDep", "open_only": "OpenOnly", "bitfinex_only": "BitfinexOnly"}
M_LABEL = {"median": "Median", "vwap": "Volume-weighted", "crh": "CRH", "gtm": "GTM", "unit_aware": "Unit-aware",
           "unit_aware_dep": "Unit-aware, one vote per unit", "open_only": "Open-rail venue alone (not a fuser)",
           "bitfinex_only": "Bitfinex alone (not a fuser)"}
SUBSETS = {"all_assets/both": "AllBoth", "all_assets/coinbase": "AllCb", "all_assets/bitstamp": "AllBst",
           "btc_eth/both": "BtcEthBoth"}
YEAR = {2017: "TwentySeventeen", 2018: "TwentyEighteen", 2019: "TwentyNineteen", 2020: "TwentyTwenty",
        2021: "TwentyTwentyOne", 2022: "TwentyTwentyTwo", 2023: "TwentyTwentyThree"}
GROUP = {"all": "AllYears", "stress:bitfinex_2017": "StressBfxTwentySeventeen",
         "stress:bitfinex_2018_19": "StressBfxTwentyEighteenNineteen", **{f"year:{y}": f"Year{w}" for y, w in YEAR.items()}}
P2_WORD = {"b1": "BOne", "b2": "BTwo", "crh": "Crh", "gtm": "Gtm", "est": "Est"}
P2_LABEL = {"b1": "$b_1$", "b2": "$b_2$", "crh": "CRH", "gtm": "GTM", "est": "Estimator"}


def load() -> dict[str, Any]:
    return json.loads(SRC_FILE.read_text())


def numbers() -> str:
    d = load()
    rows: list[tuple[str, str, str]] = []
    for sub, sw in SUBSETS.items():
        for g, gw in GROUP.items():
            for m, s in d["part1"][sub][g].items():
                where = f"{SRC} part1/{sub}/{g}/{m}"
                base = f"NumT{sw}{gw}{M_WORD[m]}"
                rows += [(base + "Hours", f"{s['hours']:,}", where + "/hours"),
                         (base + "Med", f"{s['median_abs_bps']:.1f}", where + "/median_abs_bps"),
                         (base + "PNinetyFive", f"{s['p95_abs_bps']:.1f}", where + "/p95_abs_bps"),
                         (base + "HoursGtFifty", f"{s['hours_gt_50']:,}", where + "/hours_gt_50")]
    for split in ("dev", "test"):
        p = d["part2"][split]
        for gname in ("pooled",):
            for m, st in p["bootstrap"][gname].items():
                if m == "b0":
                    continue
                w = f"{SRC} part2/{split}/bootstrap/{gname}/{m}"
                base = f"NumTPart{split.capitalize()}{P2_WORD[m]}"
                rows += [(base, _num(st["point"], 3), w), (base + "Lo", _num(st["lo"], 3), w + " (95% lower)"),
                         (base + "Hi", _num(st["hi"], 3), w + " (95% upper)")]
        for tag, key in (("Crh", "diff_est_minus_crh"), ("Gtm", "diff_est_minus_gtm")):
            st = p[key]["pooled"]
            w = f"{SRC} part2/{split}/{key}/pooled"
            base = f"NumTPart{split.capitalize()}EstMinus{tag}"
            rows += [(base, _num(st["point"], 3), w), (base + "Lo", _num(st["lo"], 3), w + " (95% lower)"),
                     (base + "Hi", _num(st["hi"], 3), w + " (95% upper)")]
    hp = d["hyperparameters"]
    rows += [("NumTWindowDays", str(hp["window_hours"] // 24), f"{SRC} hyperparameters/window_hours / 24"),
             ("NumTGtmAlpha", f"{hp['gtm']['alpha']:.0f}", f"{SRC} hyperparameters/gtm/alpha"),
             ("NumTGtmBeta", f"{hp['gtm']['beta']:.0f}", f"{SRC} hyperparameters/gtm/beta")]
    names = [r[0] for r in rows]
    assert len(names) == len(set(names)) and all(n.isalpha() for n in names), "macro names must be unique letters"
    body = "\n".join(f"\\newcommand{{\\{n}}}{{{v}}} % {s}" for n, v, s in rows)
    return f"{HEADER}\n{body}\n"


def table() -> str:
    d = load()
    p1 = d["part1"]["all_assets/both"]
    cols = ("all", "stress:bitfinex_2017", "stress:bitfinex_2018_19", "year:2023")

    def cell(m: str, g: str) -> str:
        s = p1[g][m]
        return f"{s['median_abs_bps']:.1f} & {s['p95_abs_bps']:.0f} & {s['hours_gt_50']:,}"

    r1 = [f"{M_LABEL[m]} & " + " & ".join(cell(m, g) for g in cols) + " \\\\" for m in M_WORD]
    t1 = ("\\begin{table*}[!tp]\n\\footnotesize\n\\caption{Error of the fused USD price against a held-out open-rail venue "
          "(leave-one-venue-out: Bitfinex and one open-rail venue are fused and scored against the other, Coinbase or Bitstamp; "
          "seven assets, 2017--2023, both references pooled). Median and 95th-percentile absolute error in bps, and hours above "
          "50 bps. CRH and GTM use a trailing 30-day window. With two sources the median, CRH and GTM coincide.}\n"
          "\\label{tab:td-index}\n\\setlength{\\tabcolsep}{3pt}\n\\begin{tabular}{@{}lcccccccccccc@{}}\n\\toprule\n"
          " & \\multicolumn{3}{c}{All hours} & \\multicolumn{3}{c}{Bitfinex 2017-04..07} & \\multicolumn{3}{c}{Bitfinex 2018-10..2019-05} "
          "& \\multicolumn{3}{c}{2023} \\\\\n"
          "Method & Med & P95 & $>$50 & Med & P95 & $>$50 & Med & P95 & $>$50 & Med & P95 & $>$50 \\\\\n\\midrule\n"
          + "\n".join(r1[:6]) + "\n\\midrule\n" + "\n".join(r1[6:]) + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n")

    def f(st: dict[str, float]) -> str:
        return f"{_num(st['point'], 3)} [{_num(st['lo'], 3)}, {_num(st['hi'], 3)}]"

    r2 = []
    for split, label in (("dev", "Dev, pooled"), ("test", "Test, pooled")):
        b = d["part2"][split]["bootstrap"]["pooled"]
        r2.append(f"{label} & " + " & ".join(f(b[m]) for m in P2_WORD) + " \\\\")
    t2 = ("\\begin{table*}[!tp]\n\\footnotesize\n\\caption{Held-out-asset correction (Bitfinex versus Coinbase), share of the mean-square "
          "gap removed, with 95\\% block-bootstrap intervals as in Table~\\ref{tab:heldout-ci}. CRH and GTM resolve the pair offset "
          "from the other visible assets' gaps with reliabilities fitted on the trailing 30 days.}\n"
          "\\label{tab:td-heldout}\n\\setlength{\\tabcolsep}{3pt}\n\\begin{tabular}{@{}llllll@{}}\n\\toprule\n"
          " & " + " & ".join(P2_LABEL[m] for m in P2_WORD) + " \\\\\n\\midrule\n" + "\n".join(r2)
          + "\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    return f"{HEADER}\n{t1}\n{t2}"


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    NUMBERS.write_text(numbers())
    TABLE.write_text(table())
    print(f"wrote {NUMBERS} and {TABLE}")


if __name__ == "__main__":
    main()
