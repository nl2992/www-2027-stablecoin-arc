"""Command-line entry point for the C3 fragmentation/persistence report."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd

from .fragmentation import fragmentation_report


LIMITATIONS = [
    "Wedges use one-minute last-trade closes; legs are not synchronized quotes and asynchronous trading alone creates apparent wedges.",
    "all_minutes_last_close carries stale closes through no-trade minutes, which mechanically inflates AR(1) persistence.",
    "all_legs_traded keeps only minutes in which every leg printed volume; it is less stale but selects on activity.",
    "Episodes are judged at observed minutes only and are censored at regime boundaries.",
    "Last-trade closes contain bid-ask bounce, which biases minute-level AR(1) persistence downward.",
    "ar1_phi reverts toward the regime-window mean; ar1_to_parity_phi reverts toward a zero wedge.",
    "Regimes are the upstream calendar labels, not estimated states.",
    "No executable cost, depth or arbitrage capacity is measured here.",
]


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


REGIME_ORDER = ("pre_crisis", "crisis", "recovery", "post", "full_sample")


def _fmt(value: float | None, digits: int = 1) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def render_markdown(report: dict, *, rule: str = "all_legs_traded", threshold: str = "25.0") -> str:
    """Tables generated from the JSON report so documents cannot drift from results."""
    lines = [f"<!-- generated by www_c3.cli from input sha256 {report['input_sha256']}; do not edit -->"]
    for name, rules in report["wedges"].items():
        lines += ["", f"**{name.upper()} wedge (bps), rule `{rule}`**", "",
                  f"| Regime | Minutes | Mean | Median abs | P95 abs | Max abs | Share >{float(threshold):g} | "
                  f"Episodes >{float(threshold):g} (median / max min) | phi (95% CI) | phi to parity |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for regime in REGIME_ORDER:
            s = rules[rule].get(regime)
            if s is None:
                continue
            t = s["thresholds"][threshold]
            ci = s["ar1_phi_ci95"] or [None, None]
            share = t["share_observed_minutes_above"]
            lines.append(
                f"| {regime} | {s['observed_minutes']:,} | {_fmt(s['mean_bps'], 2)} | {_fmt(s['median_abs_bps'], 2)} | "
                f"{_fmt(s['p95_abs_bps'])} | {_fmt(s['max_abs_bps'])} | {_fmt(None if share is None else 100 * share)}% | "
                f"{t['episodes']} ({_fmt(t['median_duration_minutes'], 0)} / {_fmt(t['max_duration_minutes'], 0)}) | "
                f"{_fmt(s['ar1_phi'], 2)} ({_fmt(ci[0], 2)}–{_fmt(ci[1], 2)}) | {_fmt(s['ar1_to_parity_phi'], 2)} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--panel", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--source-revision", required=True)
    parser.add_argument("--bootstrap-draws", type=int, default=500)
    parser.add_argument("--markdown", type=Path, help="optional generated table file")
    args = parser.parse_args()
    if not args.panel.is_file():
        raise SystemExit(f"panel not found: {args.panel}")
    result = {
        "checkpoint": "C3",
        "input_sha256": sha256(args.panel),
        "input_bytes": args.panel.stat().st_size,
        "source_revision": args.source_revision,
        "bootstrap": {"method": "moving-block over adjacent pairs", "block_minutes": 60,
                      "draws": args.bootstrap_draws, "seed": 20230310},
        **fragmentation_report(pd.read_parquet(args.panel), bootstrap_draws=args.bootstrap_draws),
        "limitations": LIMITATIONS,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    print(f"WROTE {args.output}")
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(render_markdown(result))
        print(f"WROTE {args.markdown}")


if __name__ == "__main__":
    main()
